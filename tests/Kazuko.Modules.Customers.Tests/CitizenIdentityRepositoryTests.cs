using System.IO;
using Dapper;
using FirebirdSql.Data.FirebirdClient;
using Kazuko.Core.Customers;
using Kazuko.Infrastructure.Customers;
using Kazuko.Infrastructure.Data;
using Xunit;

namespace Kazuko.Modules.Customers.Tests;

public sealed class CitizenIdentityRepositoryTests
{
    [Fact]
    public async Task Identity_lookup_and_save_are_scoped_and_simultaneous_saves_cannot_duplicate()
    {
        var original = FirebirdDatabase.Profile;
        var path = Path.Combine(Path.GetTempPath(), $"kazuko-cccd-{Guid.NewGuid():N}.fdb");
        var profile = original with { DatabasePath = path, UseEmbedded = true };
        try
        {
            FbConnection.CreateDatabase(FirebirdDatabase.BuildConnectionString(profile));
            FirebirdDatabase.ApplyProfileForCurrentProcess(profile);
            await using var db = FirebirdDatabase.CreateConnection();
            await db.OpenAsync();
            foreach (var statement in new[]
            {
                "CREATE TABLE AUDIT_LOG (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USER_ID BIGINT, USERNAME VARCHAR(100), BRANCH_ID BIGINT, EVENT_TYPE VARCHAR(100), ENTITY_TYPE VARCHAR(100), ENTITY_ID VARCHAR(100), EVENT_DATA BLOB SUB_TYPE TEXT, MACHINE_NAME VARCHAR(255), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP)",
                "CREATE TABLE COMPANIES (ID BIGINT, CODE VARCHAR(30), IS_ACTIVE BOOLEAN DEFAULT TRUE)",
                "CREATE TABLE BRANCHES (ID BIGINT, COMPANY_ID BIGINT, IS_ACTIVE BOOLEAN)",
                "INSERT INTO BRANCHES VALUES (1, 1, TRUE)",
                "CREATE TABLE CUSTOMER_GROUPS (ID BIGINT, COMPANY_ID BIGINT, CODE VARCHAR(30), NAME VARCHAR(100), IS_ACTIVE BOOLEAN, IS_DEFAULT BOOLEAN, MIN_POINTS INTEGER)",
                """
                CREATE TABLE CUSTOMERS (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    COMPANY_ID BIGINT, CREATED_BRANCH_ID BIGINT, CUSTOMER_GROUP_ID BIGINT,
                    CODE VARCHAR(30), CUSTOMER_TYPE VARCHAR(30), NAME VARCHAR(100),
                    PHONE VARCHAR(30), EMAIL VARCHAR(100), ADDRESS VARCHAR(255), GENDER VARCHAR(30), REGION VARCHAR(100),
                    OCCUPATION VARCHAR(100), MEMBERSHIP_RANK VARCHAR(30), TAX_CODE VARCHAR(30), NOTES VARCHAR(255),
                    OPENING_POINTS INTEGER DEFAULT 0, CREDIT_LIMIT DECIMAL(18,2) DEFAULT 0,
                    BIRTH_OR_ESTABLISHED_DATE DATE, JOIN_DATE DATE, PHOTO_PATH VARCHAR(255),
                    ID_ISSUE_DATE DATE, ID_ISSUE_PLACE VARCHAR(100), BANK_NAME VARCHAR(100), BUYER_NAME VARCHAR(100), BANK_ACCOUNT_NUMBER VARCHAR(100),
                    IS_ACTIVE BOOLEAN DEFAULT TRUE, IS_WALK_IN BOOLEAN DEFAULT FALSE NOT NULL,
                    CREATED_BY BIGINT, UPDATED_BY BIGINT, UPDATED_AT TIMESTAMP)
                """,

                "INSERT INTO COMPANIES VALUES (1, 'KAZUKO', TRUE)",
                "INSERT INTO COMPANIES VALUES (2, 'OTHER', TRUE)",
                "INSERT INTO BRANCHES VALUES (2, 2, TRUE)",
                "INSERT INTO BRANCHES VALUES (3, 1, FALSE)",
                "INSERT INTO BRANCHES VALUES (4, 1, TRUE)",
                "INSERT INTO CUSTOMER_GROUPS VALUES (1, 1, 'REG', 'Regular', TRUE, TRUE, 0)",
                "INSERT INTO CUSTOMER_GROUPS VALUES (2, 2, 'REG', 'Regular', TRUE, TRUE, 0)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CODE, NAME, TAX_CODE, IS_ACTIVE) VALUES (100, 1, 'KH100', 'Current', '012345678901', TRUE)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CODE, NAME, TAX_CODE, IS_ACTIVE) VALUES (101, 1, 'KH101', 'Old ID', '123456789', FALSE)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CODE, NAME, TAX_CODE, IS_WALK_IN) VALUES (102, 1, 'KH102', 'System', '012345678901', TRUE)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CODE, NAME, TAX_CODE) VALUES (103, 2, 'KH103', 'Other', '012345678901')"
            }) await db.ExecuteAsync(statement);

            await db.ExecuteAsync("UPDATE CUSTOMERS SET CUSTOMER_GROUP_ID=CASE WHEN COMPANY_ID=1 THEN 1 ELSE 2 END");
            var repo = new FirebirdCustomerRepository();
            var session = CustomerTestContext.Session().Current!;
            var matches = await repo.FindIdentityMatchesAsync("012345678901", "123456789", null, session);
            Assert.Equal(new long[] {100, 102, 101}, matches.Select(x => x.Id));
            Assert.Contains(matches, x => !x.IsActive);
            Assert.Contains(matches, x => x.IsWalkIn);
            Assert.DoesNotContain(await repo.FindIdentityMatchesAsync("012345678901", "123456789", 100, session), x => x.Id == 100);
            Assert.Equal(103, Assert.Single(await repo.FindIdentityMatchesAsync("012345678901", null, null, session with { BranchId = 2 })).Id);
            Assert.Empty(await repo.FindIdentityMatchesAsync("012345678901", null, null, session with { BranchId = 3 }));
            Assert.Null(await repo.GetByIdAsync(103, session: session));
            Assert.NotNull(await repo.GetByIdAsync(103, session: session with { BranchId = 2 }));

            var request = new CustomerSaveRequest(null, "Scanned", 1, "", "0901234567", "", null, 0,
                "012345678901", "", "", "", "", "", null, 0, true, null, null, "", "", "", "");
            var duplicate = await Assert.ThrowsAsync<InvalidOperationException>(() => repo.SaveAsync(request, session));
            Assert.Contains("CCCD/CMND", duplicate.Message);
            duplicate = await Assert.ThrowsAsync<InvalidOperationException>(() => repo.SaveAsync(request with { TaxCode = "012345678902", PreviousIdentityNumber = "123456789" }, session));
            Assert.Contains("CCCD/CMND", duplicate.Message);
            await Assert.ThrowsAsync<InvalidOperationException>(() => repo.SaveAsync(request with { TaxCode = "012345678903", CustomerGroupId = 2 }, session));
            var other = await repo.SaveAsync(request with { TaxCode = "012345678904", CustomerGroupId = 2 }, session with { BranchId = 2 });
            var created = await repo.SaveAsync(request with { TaxCode = "012345678904" }, session);
            await repo.SaveAsync(request with { Id = created.Id, TaxCode = "012345678904" }, session);
            Assert.NotEqual(other.Id, created.Id);
            // The mixed tax-code field keeps its existing policy for non-identity tax codes.
            await repo.SaveAsync(request with { TaxCode = "1234567890" }, session);
            await repo.SaveAsync(request with { TaxCode = "1234567890" }, session);

            for (var round = 990; round < 995; round++)
            {
                var number = $"012345678{round}";
                var start = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
                async Task<Exception?> SaveAt(long branch)
                {
                    await start.Task;
                    try { await repo.SaveAsync(request with { TaxCode = number }, session with { BranchId = branch }); return null; }
                    catch (Exception error) { return error; }
                }
                var first = Task.Run(() => SaveAt(1));
                var second = Task.Run(() => SaveAt(4));
                start.SetResult();
                var results = await Task.WhenAll(first, second);
                Assert.Single(results, x => x is null);
                var blocked = Assert.IsType<InvalidOperationException>(Assert.Single(results, x => x is not null));
                Assert.Contains("CCCD/CMND", blocked.Message);
                Assert.Equal(1, await db.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM CUSTOMERS WHERE COMPANY_ID=1 AND TAX_CODE=@number", new { number }));
            }
        }
        finally
        {
            FbConnection.ClearAllPools();
            FirebirdDatabase.ApplyProfileForCurrentProcess(original);
            if (File.Exists(path)) File.Delete(path);
        }
    }
}
