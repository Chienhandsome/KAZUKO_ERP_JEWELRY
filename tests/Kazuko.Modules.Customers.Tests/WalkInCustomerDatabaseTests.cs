using System.IO;
using Dapper;
using FirebirdSql.Data.FirebirdClient;
using Kazuko.Core.Customers;
using Kazuko.Core.Reports;
using Kazuko.Core.Sales;
using Kazuko.Core.Finance;
using Kazuko.Infrastructure.Sales;
using Kazuko.Infrastructure.Production;
using Kazuko.Infrastructure.Customers;
using Kazuko.Infrastructure.Data;
using Kazuko.Infrastructure.Reports;
using Xunit;

namespace Kazuko.Modules.Customers.Tests;

public sealed class WalkInCustomerDatabaseTests
{
    [Fact]
    public async Task Persisted_kind_drives_mapping_filters_and_backend_protection()
    {
        var original = FirebirdDatabase.Profile;
        var path = Path.Combine(Path.GetTempPath(), $"kazuko-walk-in-{Guid.NewGuid():N}.fdb");
        var profile = original with { DatabasePath = path, UseEmbedded = true };
        try
        {
            FbConnection.CreateDatabase(FirebirdDatabase.BuildConnectionString(profile));
            FirebirdDatabase.ApplyProfileForCurrentProcess(profile);
            await using var db = FirebirdDatabase.CreateConnection();
            await db.OpenAsync();
            foreach (var statement in new[]
            {
                "CREATE TABLE AUDIT_LOG (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USER_ID BIGINT, USERNAME VARCHAR(100), BRANCH_ID BIGINT, EVENT_TYPE VARCHAR(100), ENTITY_TYPE VARCHAR(100), ENTITY_ID VARCHAR(100), EVENT_DATA BLOB SUB_TYPE TEXT, MACHINE_NAME VARCHAR(255), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP)",
                "CREATE TABLE COMPANIES (ID BIGINT, CODE VARCHAR(30), IS_ACTIVE BOOLEAN DEFAULT TRUE)",
                "CREATE TABLE BRANCHES (ID BIGINT, COMPANY_ID BIGINT, IS_ACTIVE BOOLEAN)",
                "INSERT INTO BRANCHES VALUES (1, 1, TRUE)",
                "CREATE TABLE CUSTOMER_GROUPS (ID BIGINT, COMPANY_ID BIGINT, CODE VARCHAR(30), NAME VARCHAR(100), IS_ACTIVE BOOLEAN, IS_DEFAULT BOOLEAN, MIN_POINTS INTEGER)",
                """
                CREATE TABLE CUSTOMERS (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    COMPANY_ID BIGINT, CREATED_BRANCH_ID BIGINT, CUSTOMER_GROUP_ID BIGINT,
                    CODE VARCHAR(30), CUSTOMER_TYPE VARCHAR(30), NAME VARCHAR(100),
                    PHONE VARCHAR(30), EMAIL VARCHAR(100), ADDRESS VARCHAR(255), GENDER VARCHAR(30), REGION VARCHAR(100),
                    OCCUPATION VARCHAR(100), MEMBERSHIP_RANK VARCHAR(30), TAX_CODE VARCHAR(30), NOTES VARCHAR(255),
                    OPENING_POINTS INTEGER DEFAULT 0, CREDIT_LIMIT DECIMAL(18,2) DEFAULT 0,
                    BIRTH_OR_ESTABLISHED_DATE DATE, JOIN_DATE DATE, PHOTO_PATH VARCHAR(255),
                    ID_ISSUE_DATE DATE, ID_ISSUE_PLACE VARCHAR(100), BANK_NAME VARCHAR(100), BUYER_NAME VARCHAR(100), BANK_ACCOUNT_NUMBER VARCHAR(100),
                    IS_ACTIVE BOOLEAN DEFAULT TRUE, IS_WALK_IN BOOLEAN DEFAULT FALSE NOT NULL,
                    CREATED_BY BIGINT, UPDATED_BY BIGINT, UPDATED_AT TIMESTAMP)
                """,
                "CREATE TABLE SALES_ORDERS (ID BIGINT, CUSTOMER_ID BIGINT, ORDER_DATE TIMESTAMP, CODE VARCHAR(30), STATUS_CODE VARCHAR(30), GRAND_TOTAL DECIMAL(18,2))",
                "CREATE TABLE ORDER_PAYMENTS (ORDER_ID BIGINT, PAYMENT_TYPE VARCHAR(30), AMOUNT DECIMAL(18,2), IS_VOIDED BOOLEAN)",
                "CREATE TABLE SALES_CHECKOUT_OFFSETS (SALES_ORDER_ID BIGINT, AMOUNT_VND DECIMAL(18,2))",
                "INSERT INTO COMPANIES (ID, CODE) VALUES (1, 'KAZUKO')",
                "INSERT INTO COMPANIES (ID, CODE) VALUES (2, 'OTHER')",
                "INSERT INTO CUSTOMER_GROUPS VALUES (1, 1, 'REGULAR', 'Regular', TRUE, TRUE, 0)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CUSTOMER_GROUP_ID, CODE, NAME, PHONE, IS_WALK_IN) VALUES (10, 1, 1, 'ARBITRARY', 'System', '0901', TRUE)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CUSTOMER_GROUP_ID, CODE, NAME, PHONE, IS_WALK_IN) VALUES (20, 1, 1, 'WALK_IN', 'Named', '0902', FALSE)",
                "INSERT INTO CUSTOMERS (ID, COMPANY_ID, CUSTOMER_GROUP_ID, CODE, NAME, PHONE, IS_WALK_IN) VALUES (30, 2, 1, 'OTHER', 'Other company', '0903', TRUE)"
            }) await db.ExecuteAsync(statement);

            var repo = new FirebirdCustomerRepository();
            var session = CustomerTestContext.Session().Current!;
            var queries = new FirebirdSalesQueryRepository();
            var options = await queries.SearchCustomersAsync("", session);
            Assert.True(options[0].IsWalkIn);
            Assert.Equal(10, options[0].Id);
            Assert.False(Assert.Single(await queries.SearchCustomersAsync("WALK_IN", session)).IsWalkIn);
            var craft = new FirebirdCraftOrderApplicationService(new LocalProductionAttachmentStore());
            Assert.Equal(20, Assert.Single(await craft.SearchCustomersAsync("", session)).Id);
            var craftDraft = new CraftOrderDraft(10, DateTime.Today, 1,
                [new("Ring", "750", 1, 1, 100, 0, 0, null)],
                [new(PaymentMethods.Cash, 10, 1, null, null)], null);
            var craftError = await Assert.ThrowsAsync<InvalidOperationException>(() => craft.CreateWithDepositAsync(craftDraft, session));
            Assert.Contains("khách lẻ", craftError.Message);
            Assert.True((await repo.GetByIdAsync(10))!.IsWalkIn);
            Assert.False((await repo.GetByIdAsync(20))!.IsWalkIn);
            Assert.Null(await repo.GetByIdAsync(30));
            Assert.Equal(20, Assert.Single(await repo.SearchAsync(new("", 0, "", null))).Id);
            Assert.Equal(10, Assert.Single(await repo.SearchAsync(new("", 0, "", null, true))).Id);
            Assert.Equal(2, (await repo.SearchAsync(new("", 0, "", null, null))).Count);
            var blocked = await Assert.ThrowsAsync<InvalidOperationException>(() => repo.SetActiveAsync(10, false, session));
            Assert.Contains("bản ghi hệ thống", blocked.Message);
            var request = new CustomerSaveRequest(10, "Changed", 1, "", "0901", "", null, 0,
                "", "", "", "", "", "", null, 0, true, null, null, "", "", "", "");
            blocked = await Assert.ThrowsAsync<InvalidOperationException>(() => repo.SaveAsync(request, session));
            Assert.Contains("bản ghi hệ thống", blocked.Message);
            Assert.Equal("System", (await repo.GetByIdAsync(10))!.Name);
            Assert.True((await repo.GetByIdAsync(10))!.IsActive);
            await repo.SetActiveAsync(20, false, session);
            Assert.False((await repo.GetByIdAsync(20))!.IsActive);
            var created = await repo.SaveAsync(request with { Id = null, Name = "New named" }, session);
            Assert.False((await repo.GetByIdAsync(created.Id))!.IsWalkIn);
            await repo.SaveAsync(request with { Id = created.Id, Name = "Updated named" }, session);
            Assert.Equal("Updated named", (await repo.GetByIdAsync(created.Id))!.Name);

            var reports = new FirebirdMasterCustomersReportService();
            Assert.All((await reports.GetAsync(new(""), session)).Rows, x => Assert.False(x.IsWalkIn));
            Assert.Equal(10, Assert.Single((await reports.GetAsync(new("", true), session)).Rows).Id);
            Assert.Equal(3, (await reports.GetAsync(new("", null), session)).ItemCount);
            // Range filtering must happen before FIRST N, including the entire last day.
            await db.ExecuteAsync("INSERT INTO SALES_ORDERS VALUES (70, 20, TIMESTAMP '2030-01-01 00:00:00', 'OUTSIDE', 'POSTED', 300)");
            await db.ExecuteAsync("INSERT INTO SALES_ORDERS VALUES (71, 20, TIMESTAMP '2025-01-01 23:59:59', 'IN_RANGE', 'POSTED', 200)");
            await db.ExecuteAsync("INSERT INTO SALES_ORDERS VALUES (72, 20, TIMESTAMP '2024-12-31 23:59:59', 'BEFORE', 'POSTED', 100)");
            var range = await repo.GetPurchaseHistoryAsync(20, 1, fromDate: new DateTime(2025, 1, 1), toDate: new DateTime(2025, 1, 1));
            Assert.Equal("IN_RANGE", Assert.Single(range).InvoiceCode);

        }
        finally
        {
            FbConnection.ClearAllPools();
            FirebirdDatabase.ApplyProfileForCurrentProcess(original);
            if (File.Exists(path)) File.Delete(path);
        }
    }
}
