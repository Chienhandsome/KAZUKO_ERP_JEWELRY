using Dapper;
using FirebirdSql.Data.FirebirdClient;
using Kazuko.Core.Authentication;
using Kazuko.Core.Suppliers;
using Kazuko.Core.UserManagement;
using Kazuko.Infrastructure.Data;
using Kazuko.Infrastructure.Suppliers;
using Kazuko.Infrastructure.UserManagement;
using Xunit;

namespace Kazuko.Modules.Suppliers.Tests;

public sealed class SupplierGroupTests
{
    [Theory]
    [InlineData(true, false, false, false, false)]
    [InlineData(false, false, false, false, false)]
    [InlineData(false, true, false, false, false)]
    [InlineData(false, true, true, false, false)]
    [InlineData(false, true, false, true, false)]
    [InlineData(false, true, false, false, true)]
    public void Group_methods_respect_admin_and_independent_CRUD_grants(bool admin, bool view, bool add, bool edit, bool delete)
    {
        var rights = new PermissionSnapshot(admin, [new(1, "CAT_SUPPLIERS", view, add, edit, delete, false)]);
        Assert.Equal(admin || view, BackendAccess.Allows("ISupplierRepository", "GetGroupDetailsAsync", [], rights));
        Assert.Equal(admin || view, BackendAccess.Allows("ISupplierRepository", "GetGroupByIdAsync", [1L], rights));
        Assert.Equal(admin || view && add, BackendAccess.Allows("ISupplierRepository", "SaveGroupAsync", [new SupplierGroupSaveRequest(null, "New", "")], rights));
        Assert.Equal(admin || view && edit, BackendAccess.Allows("ISupplierRepository", "SaveGroupAsync", [new SupplierGroupSaveRequest(1, "Edit", "")], rights));
        Assert.Equal(admin || view && delete, BackendAccess.Allows("ISupplierRepository", "DeleteGroupAsync", [1L], rights));
        Assert.False(BackendAccess.Allows("ISupplierRepository", "UnmappedMethodAsync", [], rights));
    }

    [Fact]
    public async Task Existing_groups_load_through_authorized_repository_with_counts_and_group_CRUD_works()
    {
        var original = FirebirdDatabase.Profile;
        var path = Path.Combine(Path.GetTempPath(), $"kazuko-supplier-groups-{Guid.NewGuid():N}.fdb");
        try
        {
            var profile = original with { DatabasePath = path, UseEmbedded = true };
            FbConnection.CreateDatabase(FirebirdDatabase.BuildConnectionString(profile));
            FirebirdDatabase.ApplyProfileForCurrentProcess(profile);
            await using (var connection = FirebirdDatabase.CreateConnection())
            {
                await connection.OpenAsync();
                foreach (var sql in new[]
                {
                    "CREATE TABLE COMPANIES (ID BIGINT, CODE VARCHAR(30))",
                    "CREATE TABLE SUPPLIER_GROUPS (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, COMPANY_ID BIGINT, CODE VARCHAR(30), NAME VARCHAR(150), DESCRIPTION VARCHAR(500), IS_ACTIVE BOOLEAN, IS_DEFAULT BOOLEAN, DISPLAY_ORDER INTEGER, CREATED_BY BIGINT, UPDATED_BY BIGINT, UPDATED_AT TIMESTAMP)",
                    "CREATE TABLE SUPPLIERS (ID BIGINT, COMPANY_ID BIGINT, SUPPLIER_GROUP_ID BIGINT)",
                    "INSERT INTO COMPANIES VALUES (1, 'KAZUKO')",
                    "INSERT INTO COMPANIES VALUES (2, 'OTHER')",
                    "INSERT INTO SUPPLIER_GROUPS (ID, COMPANY_ID, CODE, NAME, IS_ACTIVE, IS_DEFAULT, DISPLAY_ORDER) VALUES (1, 1, 'GOLD', 'Vàng', TRUE, TRUE, 0)",
                    "INSERT INTO SUPPLIER_GROUPS (ID, COMPANY_ID, CODE, NAME, IS_ACTIVE, IS_DEFAULT, DISPLAY_ORDER) VALUES (2, 1, 'GEMS', 'Đá quý', TRUE, FALSE, 1)",
                    "INSERT INTO SUPPLIER_GROUPS (ID, COMPANY_ID, CODE, NAME, IS_ACTIVE, IS_DEFAULT, DISPLAY_ORDER) VALUES (3, 2, 'OTHER', 'Other company', TRUE, FALSE, 0)",
                    "ALTER TABLE SUPPLIER_GROUPS ALTER COLUMN ID RESTART WITH 10",
                    "INSERT INTO SUPPLIERS VALUES (1, 1, 1)",
                    "INSERT INTO SUPPLIERS VALUES (2, 1, 2)",
                    "INSERT INTO SUPPLIERS VALUES (3, 2, 1)"
                }) await connection.ExecuteAsync(sql);
            }
            var session = new CurrentSessionAccessor();
            session.Set(new(1, "admin", "Admin", "ADMIN", 1, "CN01", "Branch 1"));
            var repo = AuthorizedServiceProxy<ISupplierRepository>.Create(new FirebirdSupplierRepository(), new AdminAuthorization(), session);
            var groups = await repo.GetGroupDetailsAsync();
            Assert.Equal(new[] { "Vàng", "Đá quý" }, groups.Select(x => x.Name));
            Assert.All(groups, group => Assert.Equal(1, group.SupplierCount));
            Assert.Equal("Vàng", (await repo.GetGroupByIdAsync(1))!.Name);
            Assert.Null(await repo.GetGroupByIdAsync(3));
            var id = await repo.SaveGroupAsync(new(null, "Group test", "New description"), session.Current!);
            Assert.Equal(0, (await repo.GetGroupByIdAsync(id))!.SupplierCount);
            await repo.SaveGroupAsync(new(id, "Group edited", "Updated description"), session.Current!);
            Assert.Equal("Group edited", (await repo.GetGroupByIdAsync(id))!.Name);
            await Assert.ThrowsAsync<InvalidOperationException>(() => repo.DeleteGroupAsync(1, session.Current!));
            await Assert.ThrowsAsync<InvalidOperationException>(() => repo.DeleteGroupAsync(2, session.Current!));
            await repo.DeleteGroupAsync(id, session.Current!);
            Assert.Null(await repo.GetGroupByIdAsync(id));
        }
        finally
        {
            FbConnection.ClearAllPools();
            FirebirdDatabase.ApplyProfileForCurrentProcess(original);
            if (File.Exists(path)) File.Delete(path);
        }
    }

    private sealed class AdminAuthorization : IAuthorizationService
    {
        public PermissionSnapshot Current { get; } = new(true, []);
        public event EventHandler? Changed { add { } remove { } }
        public Task RefreshAsync(CancellationToken cancellationToken = default) => Task.CompletedTask;
        public void Clear() { }
        public Task DemandAsync(IEnumerable<PermissionRequirement> requirements, CancellationToken cancellationToken = default) => Task.CompletedTask;
    }
}
