-- Đồng bộ sequence FINISHED_PRODUCT với mã lớn nhất hiện có (TP-2026-000010)
-- Chạy 1 lần duy nhất

INSERT INTO DOCUMENT_SEQUENCES (DOCUMENT_TYPE, BRANCH_ID, YEAR_NO, LAST_NUMBER, UPDATED_AT)
SELECT 'FINISHED_PRODUCT', BRANCH_ID, 2026, 10, CURRENT_TIMESTAMP
FROM (SELECT DISTINCT BRANCH_ID FROM FINISHED_PRODUCTS WHERE CODE LIKE 'TP-2026-%') B
WHERE NOT EXISTS (
    SELECT 1 FROM DOCUMENT_SEQUENCES
    WHERE DOCUMENT_TYPE = 'FINISHED_PRODUCT' AND YEAR_NO = 2026
);

