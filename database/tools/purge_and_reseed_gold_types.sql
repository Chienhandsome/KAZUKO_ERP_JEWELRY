        SELECT DISTINCT SOI.ORDER_ID FROM SALES_ORDER_ITEMS SOI
        JOIN FINISHED_PRODUCTS F ON F.ID = SOI.FINISHED_PRODUCT_ID
        WHERE F.GOLD_PURITY IN ('585', '750', '999', '9999'));

DELETE FROM ORDER_ITEM_DESIGNS
 WHERE ORDER_ID IN (15, 16, 17);

