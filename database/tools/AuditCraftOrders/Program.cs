using System.Text.Json;
using Dapper;
using FirebirdSql.Data.FirebirdClient;
using Kazuko.Infrastructure.Data;

// Read-only diagnostic. No posting, data correction or schema migration.
if (args.Length is < 1 or > 2) throw new ArgumentException("Usage: AuditCraftOrders <database-path> [--schema]");
var path = Path.GetFullPath(args[0]);
FirebirdDatabase.ApplyProfileForCurrentProcess(ConnectionProfileStore.Load(path) with { DatabasePath = path });
await using var db = FirebirdDatabase.CreateConnection();
await db.OpenAsync();
await using var tx = await db.BeginTransactionAsync(new FbTransactionOptions
{
    TransactionBehavior = FbTransactionBehavior.Read | FbTransactionBehavior.Concurrency | FbTransactionBehavior.Wait
});
if (args.Length == 2 && args[1] == "--schema")
{
    await Dump("schema", """
        SELECT TRIM(RDB$RELATION_NAME) AS TABLE_NAME, LIST(TRIM(RDB$FIELD_NAME), ',') AS FIELDS
        FROM RDB$RELATION_FIELDS
        WHERE RDB$RELATION_NAME IN ('SALES_ORDERS','SALES_ORDER_ITEMS','ORDER_PAYMENTS',
            'PRODUCTION_ORDERS','PRODUCTION_ORDER_LINES','PRODUCTION_QC_UNITS','PRODUCTION_MATERIAL_BALANCES',
            'FINISHED_PRODUCTS','FINISHED_PRODUCT_DOCUMENT_LINES','FINISHED_PRODUCT_MOVEMENTS',
            'FINANCIAL_SETTLEMENTS','FINANCIAL_SETTLEMENT_ALLOCATIONS','FINANCIAL_SETTLEMENT_APPLICATIONS',
            'CASH_VOUCHERS','PAYABLE_DEBTS','RECEIVABLE_DEBTS','WORKER_GOLD_DEBTS','WORKER_GOLD_DEBT_PAYMENTS')
        GROUP BY RDB$RELATION_NAME ORDER BY RDB$RELATION_NAME
        """);
    return;
}
await Dump("orders", """
    SELECT O.ID, O.CODE, O.ORDER_TYPE, O.STATUS_CODE, O.COMPANY_ID, O.BRANCH_ID, O.CUSTOMER_ID,
           O.SUBTOTAL, O.DISCOUNT_AMOUNT, O.TAX_AMOUNT, O.GRAND_TOTAL,
           O.FINISHED_GOODS_ISSUE_DOCUMENT_ID, O.FINISHED_GOODS_ISSUED_AT
    FROM SALES_ORDERS O WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE
    """);
await Dump("payments", """
    SELECT P.* FROM ORDER_PAYMENTS P JOIN SALES_ORDERS O ON O.ID=P.ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE,P.ID
    """);
await Dump("production", """
    SELECT P.* FROM PRODUCTION_ORDERS P JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE,P.ID
    """);
await Dump("quoted_lines", """
    SELECT O.CODE AS ORDER_CODE, I.ID, I.LINE_NUMBER, I.PRODUCT_NAME, I.GOLD_PURITY,
           I.QUANTITY, I.ESTIMATED_WEIGHT, I.GOLD_UNIT_PRICE, I.LABOR_AMOUNT, I.STONE_AMOUNT,
           I.SURCHARGE_AMOUNT, I.LINE_SUBTOTAL, I.DISCOUNT_AMOUNT, I.TAX_AMOUNT, I.LINE_TOTAL
    FROM SALES_ORDER_ITEMS I JOIN SALES_ORDERS O ON O.ID=I.ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE,I.LINE_NUMBER
    """);
await Dump("production_lines", """
    SELECT O.CODE AS ORDER_CODE, P.CODE AS PRODUCTION_CODE, L.*
    FROM PRODUCTION_ORDER_LINES L JOIN PRODUCTION_ORDERS P ON P.ID=L.PRODUCTION_ORDER_ID
    JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE,L.LINE_NUMBER
    """);
await Dump("products", """
    SELECT O.CODE AS ORDER_CODE, F.PRODUCT_NAME, F.STATUS_CODE, F.LOCATION_ID,
           COUNT(*) AS UNITS, SUM(F.TOTAL_WEIGHT) AS TOTAL_WEIGHT, SUM(F.GOLD_WEIGHT) AS GOLD_WEIGHT,
           SUM(F.STONE_WEIGHT) AS STONE_WEIGHT, SUM(F.MATERIAL_COST) AS MATERIAL_COST,
           SUM(F.LABOR_COST) AS LABOR_COST, SUM(F.NON_GOLD_MATERIAL_COST) AS OTHER_COST,
           SUM(F.TOTAL_COST) AS TOTAL_COST, MIN(F.CODE) AS FIRST_SERIAL, MAX(F.CODE) AS LAST_SERIAL,
           COUNT(F.PRODUCTION_QC_UNIT_ID) AS QC_LINKS
    FROM FINISHED_PRODUCTS F JOIN SALES_ORDERS O ON O.ID=F.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002')
    GROUP BY O.CODE,F.PRODUCT_NAME,F.STATUS_CODE,F.LOCATION_ID ORDER BY O.CODE,F.PRODUCT_NAME
    """);
await Dump("stock_documents", """
    SELECT D.* FROM STOCK_DOCUMENTS D
    WHERE D.SALES_ORDER_ID IN (SELECT ID FROM SALES_ORDERS WHERE CODE IN ('DH-2026-000001','DH-2026-000002'))
       OR D.PRODUCTION_ORDER_ID IN (SELECT P.ID FROM PRODUCTION_ORDERS P JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
                                   WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002'))
    ORDER BY D.ID
    """);
await Dump("finished_document_lines", """
    SELECT D.ID AS DOCUMENT_ID, D.CODE, D.DOCUMENT_TYPE, D.STATUS_CODE, COUNT(*) AS LINES,
           COUNT(DISTINCT L.FINISHED_PRODUCT_ID) AS DISTINCT_SERIALS,
           SUM(L.UNIT_COST) AS DOCUMENT_VALUE, SUM(L.GOLD_WEIGHT_CHI) AS GOLD_WEIGHT,
           SUM(L.LABOR_COST) AS LABOR_COST, SUM(L.NON_GOLD_COST) AS OTHER_COST,
           MIN(L.SOURCE_LOCATION_ID) AS SOURCE_LOCATION, MIN(L.DESTINATION_LOCATION_ID) AS DEST_LOCATION
    FROM FINISHED_PRODUCT_DOCUMENT_LINES L JOIN STOCK_DOCUMENTS D ON D.ID=L.DOCUMENT_ID
    WHERE D.PRODUCTION_ORDER_ID IN (SELECT P.ID FROM PRODUCTION_ORDERS P JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
                                  WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002'))
       OR D.SALES_ORDER_ID IN (SELECT ID FROM SALES_ORDERS WHERE CODE IN ('DH-2026-000001','DH-2026-000002'))
    GROUP BY D.ID,D.CODE,D.DOCUMENT_TYPE,D.STATUS_CODE ORDER BY D.ID
    """);
await Dump("movement_per_serial", """
    SELECT O.CODE AS ORDER_CODE, F.CODE AS SERIAL, F.STATUS_CODE,
           SUM(M.QUANTITY_CHANGE) AS NET_QUANTITY,
           SUM(CASE WHEN M.MOVEMENT_TYPE='IN' THEN 1 ELSE 0 END) AS INS,
           SUM(CASE WHEN M.MOVEMENT_TYPE='OUT' THEN 1 ELSE 0 END) AS OUTS,
           SUM(CASE WHEN M.DOCUMENT_TYPE='FINISHED_GOODS_ISSUE' THEN 1 ELSE 0 END) AS DELIVERY_MOVEMENTS
    FROM FINISHED_PRODUCTS F JOIN SALES_ORDERS O ON O.ID=F.SALES_ORDER_ID
    LEFT JOIN FINISHED_PRODUCT_MOVEMENTS M ON M.FINISHED_PRODUCT_ID=F.ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002')
    GROUP BY O.CODE,F.CODE,F.STATUS_CODE ORDER BY O.CODE,F.CODE
    """);
await Dump("settlements_and_vouchers", """
    SELECT O.CODE AS ORDER_CODE,P.ID AS PAYMENT_ID,P.AMOUNT AS PAYMENT_AMOUNT,P.IS_VOIDED,
           S.CODE AS SETTLEMENT_CODE,S.STATUS_CODE AS SETTLEMENT_STATUS,S.SETTLEMENT_TYPE,
           S.PARTY_TYPE,S.PARTY_ID,S.TOTAL_AMOUNT_VND AS SETTLEMENT_TOTAL,
           A.ID AS ALLOCATION_ID,A.AMOUNT_VND AS ALLOCATION_AMOUNT,A.PAYMENT_METHOD,
           A.CASH_FUND_ID,A.BANK_ACCOUNT_ID,V.CODE AS VOUCHER_CODE,V.STATUS_CODE AS VOUCHER_STATUS,
           V.VOUCHER_TYPE,V.AMOUNT_VND AS VOUCHER_AMOUNT,V.CASH_FUND_ID AS VOUCHER_FUND,
           V.SOURCE_DOCUMENT_TYPE,V.SOURCE_DOCUMENT_ID,V.SOURCE_ALLOCATION_TYPE,V.SOURCE_ALLOCATION_ID,
           S.BRANCH_ID AS SETTLEMENT_BRANCH,V.BRANCH_ID AS VOUCHER_BRANCH,
           (SELECT SUM(X.AMOUNT_VND) FROM FINANCIAL_SETTLEMENT_APPLICATIONS X
            WHERE X.SETTLEMENT_ID=S.ID AND X.TARGET_TYPE='SALES_ORDER' AND X.TARGET_ID=O.ID) AS ORDER_APPLIED
    FROM ORDER_PAYMENTS P JOIN SALES_ORDERS O ON O.ID=P.ORDER_ID
    LEFT JOIN FINANCIAL_SETTLEMENTS S ON S.ID=P.FINANCIAL_SETTLEMENT_ID
    LEFT JOIN FINANCIAL_SETTLEMENT_ALLOCATIONS A ON A.ID=P.FINANCIAL_SETTLEMENT_ALLOCATION_ID
    LEFT JOIN CASH_VOUCHERS V ON V.ID=P.CASH_VOUCHER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY O.CODE,P.ID
    """);
await Dump("customer_debts", """
    SELECT D.* FROM RECEIVABLE_DEBTS D JOIN SALES_ORDERS O ON O.ID=D.ORIGIN_DOCUMENT_ID
    WHERE D.ORIGIN_DOCUMENT_TYPE='SALES_ORDER' AND O.CODE IN ('DH-2026-000001','DH-2026-000002')
    ORDER BY O.CODE,D.ID
    """);
await Dump("worker_payables", """
    SELECT O.CODE AS ORDER_CODE, P.CODE AS PRODUCTION_CODE, D.*
    FROM PAYABLE_DEBTS D JOIN PRODUCTION_ORDERS P ON P.ID=D.ORIGIN_DOCUMENT_ID
    JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE D.ORIGIN_DOCUMENT_TYPE='PRODUCTION_ORDER' AND O.CODE IN ('DH-2026-000001','DH-2026-000002')
    ORDER BY O.CODE,D.ID
    """);
await Dump("qc_totals", """
    SELECT P.CODE AS PRODUCTION_CODE,U.STATUS_CODE,COUNT(*) AS UNITS,
           SUM(U.LABOR_COST_SNAPSHOT) AS LABOR_COST,SUM(U.ACTUAL_GOLD_WEIGHT) AS ACTUAL_GOLD_WEIGHT,
           COUNT(U.FINISHED_PRODUCT_ID) AS PRODUCT_LINKS
    FROM PRODUCTION_QC_UNITS U JOIN PRODUCTION_ORDERS P ON P.ID=U.PRODUCTION_ORDER_ID
    JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') GROUP BY P.CODE,U.STATUS_CODE ORDER BY P.CODE
    """);
await Dump("material_balances", """
    SELECT P.CODE AS PRODUCTION_CODE,B.* FROM PRODUCTION_MATERIAL_BALANCES B
    JOIN PRODUCTION_ORDERS P ON P.ID=B.PRODUCTION_ORDER_ID JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY P.CODE,B.ID
    """);
await Dump("worker_gold_debts", """
    SELECT D.*,COALESCE((SELECT SUM(X.WEIGHT_PAID_CHI) FROM WORKER_GOLD_DEBT_PAYMENTS X WHERE X.DEBT_ID=D.ID),0) AS PAYMENTS_WEIGHT
    FROM WORKER_GOLD_DEBTS D JOIN PRODUCTION_ORDERS P ON P.ID=D.PRODUCTION_ORDER_ID
    JOIN SALES_ORDERS O ON O.ID=P.SALES_ORDER_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002') ORDER BY D.ID
    """);
await Dump("product_specification", """
    SELECT O.CODE AS ORDER_CODE,F.PRODUCT_NAME,F.GOLD_PURITY,G.CODE AS GOLD_TYPE_CODE,
           PG.NAME AS PRODUCT_GROUP,F.SALES_ORDER_ITEM_ID,COUNT(*) AS UNITS,
           MIN(F.TOTAL_WEIGHT) AS UNIT_TOTAL_WEIGHT,MIN(F.GOLD_WEIGHT) AS UNIT_GOLD_WEIGHT,
           MIN(F.STONE_WEIGHT) AS UNIT_STONE_WEIGHT,MIN(F.LABOR_COST) AS UNIT_LABOR_COST,
           MIN(F.TOTAL_COST) AS UNIT_TOTAL_COST
    FROM FINISHED_PRODUCTS F JOIN SALES_ORDERS O ON O.ID=F.SALES_ORDER_ID
    LEFT JOIN GOLD_TYPES G ON G.ID=F.GOLD_TYPE_ID
    LEFT JOIN FINISHED_PRODUCT_GROUPS PG ON PG.ID=F.FINISHED_PRODUCT_GROUP_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002')
    GROUP BY O.CODE,F.PRODUCT_NAME,F.GOLD_PURITY,G.CODE,PG.NAME,F.SALES_ORDER_ITEM_ID ORDER BY O.CODE,F.PRODUCT_NAME
    """);
await Dump("independent_settlement_totals", """
    SELECT O.CODE AS ORDER_CODE,S.CODE AS SETTLEMENT_CODE,S.STATUS_CODE,S.TOTAL_AMOUNT_VND,
           SUM(X.AMOUNT_VND) AS APPLIED_TO_ORDER,
           (SELECT SUM(A.AMOUNT_VND) FROM FINANCIAL_SETTLEMENT_ALLOCATIONS A WHERE A.SETTLEMENT_ID=S.ID) AS ALLOCATED,
           (SELECT COUNT(*) FROM ORDER_PAYMENTS P WHERE P.ORDER_ID=O.ID AND P.FINANCIAL_SETTLEMENT_ID=S.ID AND P.IS_VOIDED=FALSE) AS ACTIVE_PAYMENT_LINKS,
           (SELECT COUNT(*) FROM CASH_VOUCHERS V WHERE V.SOURCE_DOCUMENT_TYPE='FINANCIAL_SETTLEMENT' AND V.SOURCE_DOCUMENT_ID=S.ID AND V.STATUS_CODE='POSTED') AS ACTIVE_VOUCHERS,
           (SELECT SUM(V.AMOUNT_VND) FROM CASH_VOUCHERS V WHERE V.SOURCE_DOCUMENT_TYPE='FINANCIAL_SETTLEMENT' AND V.SOURCE_DOCUMENT_ID=S.ID AND V.STATUS_CODE='POSTED') AS VOUCHER_TOTAL
    FROM SALES_ORDERS O JOIN FINANCIAL_SETTLEMENT_APPLICATIONS X ON X.TARGET_TYPE='SALES_ORDER' AND X.TARGET_ID=O.ID
    JOIN FINANCIAL_SETTLEMENTS S ON S.ID=X.SETTLEMENT_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002')
    GROUP BY O.ID,O.CODE,S.ID,S.CODE,S.STATUS_CODE,S.TOTAL_AMOUNT_VND ORDER BY O.CODE,S.ID
    """);
await Dump("issue_price_snapshots", """
    SELECT O.CODE AS ORDER_CODE,L.GOLD_PRICE_CODE,L.GOLD_PRICE_PER_CHI,
           COUNT(*) AS UNITS,SUM(L.GOLD_WEIGHT_CHI) AS GOLD_WEIGHT,
           SUM(L.UNIT_COST) AS ISSUE_VALUE,SUM(F.TOTAL_COST) AS RECEIPT_COST,
           SUM(L.LABOR_COST) AS ISSUE_LABOR_COST,SUM(F.LABOR_COST) AS RECEIPT_LABOR_COST
    FROM SALES_ORDERS O JOIN FINISHED_PRODUCT_DOCUMENT_LINES L ON L.DOCUMENT_ID=O.FINISHED_GOODS_ISSUE_DOCUMENT_ID
    JOIN FINISHED_PRODUCTS F ON F.ID=L.FINISHED_PRODUCT_ID
    WHERE O.CODE IN ('DH-2026-000001','DH-2026-000002')
    GROUP BY O.CODE,L.GOLD_PRICE_CODE,L.GOLD_PRICE_PER_CHI ORDER BY O.CODE,L.GOLD_PRICE_CODE
    """);
await tx.RollbackAsync();

async Task Dump(string name, string sql)
{
    Console.WriteLine(name + ": " + JsonSerializer.Serialize(await db.QueryAsync(sql, transaction: tx)));
}
