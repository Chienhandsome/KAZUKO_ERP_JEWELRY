-- Step 3: Create SUPPLIER_GROUPS table
CREATE TABLE SUPPLIER_GROUPS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    CODE VARCHAR(30) CHARACTER SET ASCII NOT NULL,
    NAME VARCHAR(150) NOT NULL,
    DESCRIPTION VARCHAR(500),
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    IS_DEFAULT BOOLEAN DEFAULT FALSE NOT NULL,
    DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_SUPPLIER_GROUPS PRIMARY KEY (ID),
    CONSTRAINT FK_SUPPLIER_GROUPS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_SUPPLIER_GROUPS_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_SUPPLIER_GROUPS_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_SUPPLIER_GROUPS_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT UQ_SUPPLIER_GROUPS_COMP_ID UNIQUE (COMPANY_ID, ID)
);

CREATE INDEX IX_SUPPLIER_GROUPS_ACTIVE ON SUPPLIER_GROUPS (COMPANY_ID, IS_ACTIVE, DISPLAY_ORDER);
COMMIT;

-- Step 4: Create SUPPLIERS table
CREATE TABLE SUPPLIERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    CREATED_BRANCH_ID BIGINT,
    SUPPLIER_GROUP_ID BIGINT NOT NULL,
    CODE VARCHAR(30) CHARACTER SET ASCII NOT NULL,
    NAME VARCHAR(200) NOT NULL,
    PHONE VARCHAR(30),
    EMAIL VARCHAR(150),
    ADDRESS VARCHAR(500),
    REGION VARCHAR(100),
    TAX_CODE VARCHAR(30) CHARACTER SET ASCII,
    CONTACT_NAME VARCHAR(100),
    CONTACT_TITLE VARCHAR(100),
    NOTES VARCHAR(1000),
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_SUPPLIERS PRIMARY KEY (ID),
    CONSTRAINT FK_SUPPLIERS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_SUPPLIERS_BRANCH FOREIGN KEY (CREATED_BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT FK_SUPPLIERS_GROUP FOREIGN KEY (COMPANY_ID, SUPPLIER_GROUP_ID) REFERENCES SUPPLIER_GROUPS (COMPANY_ID, ID),
    CONSTRAINT FK_SUPPLIERS_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_SUPPLIERS_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_SUPPLIERS_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT UQ_SUPPLIERS_COMP_ID UNIQUE (COMPANY_ID, ID)
);

CREATE INDEX IX_SUPPLIERS_COMPANY_ACTIVE ON SUPPLIERS (COMPANY_ID, IS_ACTIVE);
CREATE INDEX IX_SUPPLIERS_GROUP ON SUPPLIERS (COMPANY_ID, SUPPLIER_GROUP_ID);
CREATE INDEX IX_SUPPLIERS_PHONE ON SUPPLIERS (COMPANY_ID, PHONE);
CREATE INDEX IX_SUPPLIERS_TAX_CODE ON SUPPLIERS (COMPANY_ID, TAX_CODE);
