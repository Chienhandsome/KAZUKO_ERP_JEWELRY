CREATE TABLE HR_EMPLOYEE_AWARDS (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID),
 BRANCH_ID BIGINT NOT NULL REFERENCES BRANCHES(ID),
 EMPLOYEE_ID BIGINT NOT NULL REFERENCES HR_EMPLOYEES(ID),
 EMPLOYEE_CODE VARCHAR(50) NOT NULL, EMPLOYEE_NAME VARCHAR(200) NOT NULL,
 EVENT_DATE DATE NOT NULL, KIND VARCHAR(20) NOT NULL, HANDLING VARCHAR(20) NOT NULL,
 AMOUNT NUMERIC(18,2) NOT NULL, DESCRIPTION VARCHAR(500) NOT NULL,
 PAY_YEAR INTEGER, PAY_MONTH INTEGER,
 STATUS VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
 REQUEST_ID CHAR(36) CHARACTER SET ASCII NOT NULL, REQUEST_HASH CHAR(64) CHARACTER SET ASCII NOT NULL,
 VOUCHER_ID BIGINT REFERENCES CASH_VOUCHERS(ID),
 CREATED_BY BIGINT REFERENCES USERS(ID), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CANCELLED_BY BIGINT REFERENCES USERS(ID), CANCELLED_AT TIMESTAMP, CANCEL_REASON VARCHAR(500),
 CONSTRAINT UQ_HR_AWARD_REQUEST UNIQUE(COMPANY_ID,REQUEST_ID),
 CONSTRAINT CK_HR_AWARD_KIND CHECK(KIND IN ('REWARD','DISCIPLINE')),
 CONSTRAINT CK_HR_AWARD_STATUS CHECK(STATUS IN ('ACTIVE','CANCELLED')),
 CONSTRAINT CK_HR_AWARD_HANDLING CHECK(
  (HANDLING='NONE' AND AMOUNT=0 AND PAY_YEAR IS NULL AND PAY_MONTH IS NULL AND VOUCHER_ID IS NULL) OR
  (HANDLING='PAYROLL' AND AMOUNT>0 AND PAY_YEAR BETWEEN 1900 AND 9998 AND PAY_MONTH BETWEEN 1 AND 12 AND PAY_YEAR IS NOT NULL AND PAY_MONTH IS NOT NULL AND VOUCHER_ID IS NULL) OR
  (HANDLING='CASH' AND AMOUNT>0 AND PAY_YEAR IS NULL AND PAY_MONTH IS NULL))
);
CREATE INDEX IX_HR_AWARD_PERIOD ON HR_EMPLOYEE_AWARDS(COMPANY_ID,PAY_YEAR,PAY_MONTH,STATUS);
CREATE INDEX IX_HR_AWARD_DATE ON HR_EMPLOYEE_AWARDS(COMPANY_ID,EVENT_DATE);
CREATE TABLE HR_PAYROLL_AWARD_LINKS (
 PERIOD_ID BIGINT NOT NULL REFERENCES HR_PAYROLL_PERIODS(ID),
 AWARD_ID BIGINT NOT NULL REFERENCES HR_EMPLOYEE_AWARDS(ID),
 CONSTRAINT PK_HR_PAY_AWARD PRIMARY KEY(PERIOD_ID,AWARD_ID),
 CONSTRAINT UQ_HR_PAY_AWARD UNIQUE(AWARD_ID)
);
ALTER TABLE HR_PAYROLL_LINES ADD RECORDED_BONUS NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE HR_PAYROLL_LINES ADD RECORDED_DEDUCTION NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE HR_PAYROLL_LINES ADD RECORDED_NOTES VARCHAR(2000) DEFAULT '' NOT NULL;
ALTER TABLE HR_PAYROLL_LINES DROP CONSTRAINT CK_HR_PAYROLL_AMOUNT;
ALTER TABLE HR_PAYROLL_LINES ADD CONSTRAINT CK_HR_PAYROLL_AMOUNT CHECK(
 SALARY>=0 AND BONUS>=0 AND DEDUCTION>=0 AND RECORDED_BONUS>=0 AND RECORDED_DEDUCTION>=0
 AND SALARY+BONUS+RECORDED_BONUS>=DEDUCTION+RECORDED_DEDUCTION);
CREATE TABLE HR_PAYROLL_PAYMENTS (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID), BRANCH_ID BIGINT NOT NULL REFERENCES BRANCHES(ID),
 PERIOD_ID BIGINT NOT NULL REFERENCES HR_PAYROLL_PERIODS(ID), EMPLOYEE_ID BIGINT NOT NULL REFERENCES HR_EMPLOYEES(ID),
 EMPLOYEE_NAME VARCHAR(200) NOT NULL, AMOUNT NUMERIC(18,2) NOT NULL, PAYMENT_DATE DATE NOT NULL,
 STATUS VARCHAR(20) NOT NULL, VOUCHER_ID BIGINT REFERENCES CASH_VOUCHERS(ID),
 CREATED_BY BIGINT REFERENCES USERS(ID), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CANCELLED_BY BIGINT REFERENCES USERS(ID), CANCELLED_AT TIMESTAMP, CANCEL_REASON VARCHAR(500),
 CONSTRAINT CK_HR_PAY_PAYMENT CHECK(AMOUNT>0 AND STATUS IN ('PENDING','POSTED','CANCELLED')),
 CONSTRAINT CK_HR_PAY_VOUCHER CHECK(STATUS='PENDING' OR VOUCHER_ID IS NOT NULL),
 CONSTRAINT UQ_HR_PAY_VOUCHER UNIQUE(VOUCHER_ID)
);
CREATE UNIQUE INDEX UQ_HR_PAY_ACTIVE ON HR_PAYROLL_PAYMENTS(PERIOD_ID,EMPLOYEE_ID) WHERE STATUS='POSTED';
