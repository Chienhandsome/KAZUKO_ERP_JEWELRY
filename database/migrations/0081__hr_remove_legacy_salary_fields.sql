/* Migration 81: remove obsolete employee base salary and allowance.
   Requires migration 80, which already copied base salary to MONTHLY_SALARY.
   Recovery: restore the pre-migration gbak backup and use the matching app build.
   The two removed values cannot be reconstructed after dropping their columns.
   Run through Invoke-KazukoMigration.ps1 (backup + SHA-256 ledger).
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_HR_LEGACY_SALARY 'Migration 80 is required before migration 81.';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
    IF (NOT EXISTS (SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 80)) THEN
        EXCEPTION EX_HR_LEGACY_SALARY;
END^
EXECUTE BLOCK AS
BEGIN
    IF (EXISTS (SELECT 1 FROM RDB$RELATION_CONSTRAINTS
                WHERE RDB$CONSTRAINT_NAME = 'CK_HR_EMP_BASE_SALARY')) THEN
        EXECUTE STATEMENT 'ALTER TABLE HR_EMPLOYEES DROP CONSTRAINT CK_HR_EMP_BASE_SALARY';
    IF (EXISTS (SELECT 1 FROM RDB$RELATION_CONSTRAINTS
                WHERE RDB$CONSTRAINT_NAME = 'CK_HR_EMP_ALLOWANCE')) THEN
        EXECUTE STATEMENT 'ALTER TABLE HR_EMPLOYEES DROP CONSTRAINT CK_HR_EMP_ALLOWANCE';
    IF (EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS
                WHERE RDB$RELATION_NAME = 'HR_EMPLOYEES' AND RDB$FIELD_NAME = 'BASE_SALARY')) THEN
        EXECUTE STATEMENT 'ALTER TABLE HR_EMPLOYEES DROP BASE_SALARY';
    IF (EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS
                WHERE RDB$RELATION_NAME = 'HR_EMPLOYEES' AND RDB$FIELD_NAME = 'ALLOWANCE')) THEN
        EXECUTE STATEMENT 'ALTER TABLE HR_EMPLOYEES DROP ALLOWANCE';
END^
SET TERM ; ^
DROP EXCEPTION EX_HR_LEGACY_SALARY;
