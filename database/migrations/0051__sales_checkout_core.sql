CREATE TABLE SALES_CHECKOUTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    BRANCH_ID BIGINT NOT NULL,
    CODE VARCHAR(40) CHARACTER SET ASCII NOT NULL,
    CHECKOUT_TYPE VARCHAR(30) CHARACTER SET ASCII NOT NULL,
    DOCUMENT_DATE DATE NOT NULL,
    CUSTOMER_ID BIGINT NOT NULL,
    SALESPERSON_ID BIGINT NOT NULL,
    SOURCE_LOCATION_ID BIGINT,
    OLD_GOLD_DESTINATION_LOCATION_ID BIGINT,
    SALE_GROSS_VND NUMERIC(18,2) NOT NULL,
    OLD_GOLD_TOTAL_VND NUMERIC(18,2) NOT NULL,
    DISCOUNT_AMOUNT_VND NUMERIC(18,2) NOT NULL,
    NET_AMOUNT_VND NUMERIC(18,2) NOT NULL,
    SALES_ORDER_ID BIGINT,
    OLD_GOLD_STOCK_DOCUMENT_ID BIGINT,
    FINANCIAL_SETTLEMENT_ID BIGINT,
    RECEIVABLE_DEBT_ID BIGINT,
    CLIENT_REQUEST_ID CHAR(36) CHARACTER SET ASCII NOT NULL,
    REQUEST_HASH CHAR(64) CHARACTER SET ASCII NOT NULL,
    STATUS_CODE VARCHAR(20) CHARACTER SET ASCII DEFAULT 'POSTED' NOT NULL,
    NOTES VARCHAR(1000),
    CREATED_BY BIGINT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_SALES_CHECKOUTS PRIMARY KEY (ID),
    CONSTRAINT FK_SC_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_SC_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT FK_SC_CUSTOMER FOREIGN KEY (COMPANY_ID, CUSTOMER_ID)
        REFERENCES CUSTOMERS (COMPANY_ID, ID),
    CONSTRAINT FK_SC_SALESPERSON FOREIGN KEY (SALESPERSON_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_SC_SOURCE_LOCATION FOREIGN KEY (SOURCE_LOCATION_ID) REFERENCES LOCATIONS (ID),
    CONSTRAINT FK_SC_OLD_GOLD_LOCATION FOREIGN KEY (OLD_GOLD_DESTINATION_LOCATION_ID)
        REFERENCES LOCATIONS (ID),
    CONSTRAINT FK_SC_SALES_ORDER FOREIGN KEY (SALES_ORDER_ID) REFERENCES SALES_ORDERS (ID),
    CONSTRAINT FK_SC_OLD_GOLD_DOCUMENT FOREIGN KEY (OLD_GOLD_STOCK_DOCUMENT_ID)
        REFERENCES STOCK_DOCUMENTS (ID),
    CONSTRAINT FK_SC_SETTLEMENT FOREIGN KEY (FINANCIAL_SETTLEMENT_ID)
        REFERENCES FINANCIAL_SETTLEMENTS (ID),
    CONSTRAINT FK_SC_RECEIVABLE FOREIGN KEY (RECEIVABLE_DEBT_ID)
        REFERENCES RECEIVABLE_DEBTS (ID),
    CONSTRAINT FK_SC_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_SC_CODE UNIQUE (BRANCH_ID, CODE),
    CONSTRAINT UQ_SC_CLIENT_REQUEST UNIQUE (BRANCH_ID, CLIENT_REQUEST_ID),
    CONSTRAINT CK_SC_TYPE CHECK (
        CHECKOUT_TYPE IN ('SALE', 'TRADE_IN', 'OLD_GOLD_PURCHASE')),
    CONSTRAINT CK_SC_STATUS CHECK (STATUS_CODE IN ('POSTED')),
    CONSTRAINT CK_SC_TOTALS CHECK (
        SALE_GROSS_VND >= 0
        AND OLD_GOLD_TOTAL_VND >= 0
        AND DISCOUNT_AMOUNT_VND >= 0
        AND DISCOUNT_AMOUNT_VND <= SALE_GROSS_VND
        AND NET_AMOUNT_VND = SALE_GROSS_VND - DISCOUNT_AMOUNT_VND - OLD_GOLD_TOTAL_VND),
    CONSTRAINT CK_SC_REQUEST_HASH CHECK (CHAR_LENGTH(TRIM(REQUEST_HASH)) = 64)
);

