/* ---- One immutable, traceable old-gold snapshot per checkout line ---- */
CREATE TABLE SALES_OLD_GOLD_LINES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CHECKOUT_ID BIGINT NOT NULL,
    LINE_NUMBER INTEGER NOT NULL,
    MATERIAL_ID BIGINT NOT NULL,
    STOCK_DOCUMENT_LINE_ID BIGINT NOT NULL,
    ITEM_QUANTITY NUMERIC(18,3) NOT NULL,
    TOTAL_WEIGHT_CHI NUMERIC(18,4) NOT NULL,
    STONE_WEIGHT_CHI NUMERIC(18,4) NOT NULL,
    IMPURITY_WEIGHT_CHI NUMERIC(18,4) NOT NULL,
    GOLD_WEIGHT_CHI NUMERIC(18,4) NOT NULL,
    VALUE_PERCENT NUMERIC(9,4) NOT NULL,
    CONVERTED_WEIGHT_CHI NUMERIC(18,4) NOT NULL,
    SOURCE_BUY_PRICE_PER_CHI NUMERIC(18,2) NOT NULL,
    APPLIED_BUY_PRICE_PER_CHI NUMERIC(18,2) NOT NULL,
    AMOUNT_VND NUMERIC(18,2) NOT NULL,
    IS_PRICE_OVERRIDE BOOLEAN DEFAULT FALSE NOT NULL,
    PRICE_OVERRIDE_REASON VARCHAR(500),
    NOTES VARCHAR(500),
    CONSTRAINT PK_SALES_OLD_GOLD_LINES PRIMARY KEY (ID),
    CONSTRAINT FK_SOGL_CHECKOUT FOREIGN KEY (CHECKOUT_ID) REFERENCES SALES_CHECKOUTS (ID),
    CONSTRAINT FK_SOGL_MATERIAL FOREIGN KEY (MATERIAL_ID) REFERENCES MATERIALS (ID),
    CONSTRAINT FK_SOGL_STOCK_LINE FOREIGN KEY (STOCK_DOCUMENT_LINE_ID)
        REFERENCES STOCK_DOCUMENT_LINES (ID),
    CONSTRAINT UQ_SOGL_LINE UNIQUE (CHECKOUT_ID, LINE_NUMBER),
    CONSTRAINT UQ_SOGL_STOCK_LINE UNIQUE (STOCK_DOCUMENT_LINE_ID),
    CONSTRAINT CK_SOGL_LINE_NUMBER CHECK (LINE_NUMBER > 0),
    CONSTRAINT CK_SOGL_ITEM_QUANTITY CHECK (ITEM_QUANTITY > 0),
    CONSTRAINT CK_SOGL_WEIGHTS CHECK (
        TOTAL_WEIGHT_CHI >= 0
        AND STONE_WEIGHT_CHI >= 0
        AND IMPURITY_WEIGHT_CHI >= 0
        AND STONE_WEIGHT_CHI + IMPURITY_WEIGHT_CHI <= TOTAL_WEIGHT_CHI
        AND GOLD_WEIGHT_CHI = TOTAL_WEIGHT_CHI - STONE_WEIGHT_CHI - IMPURITY_WEIGHT_CHI
        AND VALUE_PERCENT BETWEEN 0 AND 100
        AND CONVERTED_WEIGHT_CHI >= 0
        AND CONVERTED_WEIGHT_CHI <= GOLD_WEIGHT_CHI),
    CONSTRAINT CK_SOGL_PRICES CHECK (
        SOURCE_BUY_PRICE_PER_CHI >= 0
        AND APPLIED_BUY_PRICE_PER_CHI >= 0
        AND AMOUNT_VND >= 0),
    CONSTRAINT CK_SOGL_OVERRIDE CHECK (
        (IS_PRICE_OVERRIDE = FALSE AND PRICE_OVERRIDE_REASON IS NULL)
        OR (IS_PRICE_OVERRIDE = TRUE
            AND PRICE_OVERRIDE_REASON IS NOT NULL
            AND TRIM(PRICE_OVERRIDE_REASON) <> ''))
);

CREATE INDEX IX_SOGL_CHECKOUT ON SALES_OLD_GOLD_LINES (CHECKOUT_ID);
CREATE INDEX IX_SOGL_MATERIAL ON SALES_OLD_GOLD_LINES (MATERIAL_ID);
CREATE INDEX IX_SOGL_STOCK_LINE ON SALES_OLD_GOLD_LINES (STOCK_DOCUMENT_LINE_ID);

