================================================================================
Migration Version: 60
Migration Name:    WAREHOUSE_BUY_SELL_PRICES
Description:       Replace the single warehouse issue price in the price-board
                   workflow with independent warehouse buy and sell prices.
Target Database:   Firebird 5.0 (Dialect 3, UTF8)
================================================================================
*/

SET AUTODDL OFF;

CREATE EXCEPTION EX_MIGRATION_CHECK 'Migration 60 validation failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 60 INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Phien ban migration 60 da ton tai.';

    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 59 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Can migration 59 truoc migration 60.';

    SELECT COUNT(*) FROM RDB$RELATIONS
    WHERE RDB$RELATION_NAME IN ('WAREHOUSE_GOLD_PRICES', 'WAREHOUSE_GOLD_PRICE_HISTORY')
    INTO :v_cnt;
    IF (:v_cnt <> 2) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Thieu bang gia vang kho hoac lich su.';
END^
SET TERM ; ^

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICES'
      AND RDB$FIELD_NAME = 'BUY_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICES ADD BUY_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICES'
      AND RDB$FIELD_NAME = 'SELL_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICES ADD SELL_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICE_HISTORY'
      AND RDB$FIELD_NAME = 'OLD_BUY_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICE_HISTORY ADD OLD_BUY_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICE_HISTORY'
      AND RDB$FIELD_NAME = 'NEW_BUY_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICE_HISTORY ADD NEW_BUY_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICE_HISTORY'
      AND RDB$FIELD_NAME = 'OLD_SELL_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICE_HISTORY ADD OLD_SELL_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICE_HISTORY'
      AND RDB$FIELD_NAME = 'NEW_SELL_PRICE_PER_CHI'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT
            'ALTER TABLE WAREHOUSE_GOLD_PRICE_HISTORY ADD NEW_SELL_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL';
END^
SET TERM ; ^

-- Step 6: Seed existing single warehouse prices into both new price columns
UPDATE WAREHOUSE_GOLD_PRICES
SET BUY_PRICE_PER_CHI = ISSUE_PRICE_PER_CHI,
    SELL_PRICE_PER_CHI = ISSUE_PRICE_PER_CHI;

UPDATE WAREHOUSE_GOLD_PRICE_HISTORY
SET OLD_BUY_PRICE_PER_CHI = OLD_PRICE_PER_CHI,
    NEW_BUY_PRICE_PER_CHI = NEW_PRICE_PER_CHI,
    OLD_SELL_PRICE_PER_CHI = OLD_PRICE_PER_CHI,
    NEW_SELL_PRICE_PER_CHI = NEW_PRICE_PER_CHI;

ALTER TABLE WAREHOUSE_GOLD_PRICES ADD CONSTRAINT CK_WGP_BUY_SELL_PRICES CHECK (
    BUY_PRICE_PER_CHI >= 0 AND SELL_PRICE_PER_CHI >= 0);

ALTER TABLE WAREHOUSE_GOLD_PRICE_HISTORY ADD CONSTRAINT CK_WGPH_BUY_SELL_PRICES CHECK (
    OLD_BUY_PRICE_PER_CHI >= 0 AND NEW_BUY_PRICE_PER_CHI >= 0
    AND OLD_SELL_PRICE_PER_CHI >= 0 AND NEW_SELL_PRICE_PER_CHI >= 0);

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICES'
      AND RDB$FIELD_NAME IN ('BUY_PRICE_PER_CHI', 'SELL_PRICE_PER_CHI')
    INTO :v_cnt;
    IF (:v_cnt <> 2) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Khong tao du hai cot gia mua/ban trong kho.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'WAREHOUSE_GOLD_PRICE_HISTORY'
      AND RDB$FIELD_NAME IN (
          'OLD_BUY_PRICE_PER_CHI', 'NEW_BUY_PRICE_PER_CHI',
          'OLD_SELL_PRICE_PER_CHI', 'NEW_SELL_PRICE_PER_CHI')
    INTO :v_cnt;
    IF (:v_cnt <> 4) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Khong tao du cot lich su gia mua/ban trong kho.';
END^
SET TERM ; ^

DROP EXCEPTION EX_MIGRATION_CHECK;
