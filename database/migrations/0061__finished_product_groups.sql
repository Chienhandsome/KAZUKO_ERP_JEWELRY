CREATE OR ALTER TRIGGER BIU_FP_AUTO_GROUP FOR FINISHED_PRODUCTS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
DECLARE VARIABLE v_code VARCHAR(30) CHARACTER SET ASCII;
BEGIN
    IF (NEW.FINISHED_PRODUCT_GROUP_ID IS NULL AND NEW.PRODUCT_NAME IS NOT NULL) THEN
    BEGIN
        v_code = CASE
            WHEN UPPER(NEW.PRODUCT_NAME) CONTAINING 'NHẪN' OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'NHAN' THEN 'RING'
            WHEN UPPER(NEW.PRODUCT_NAME) CONTAINING 'BÔNG' OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'BONG' THEN 'EARRING'
            WHEN UPPER(NEW.PRODUCT_NAME) CONTAINING 'LẮC' OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'LAC'
              OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'VÒNG' OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'VONG' THEN 'BRACELET'
            WHEN UPPER(NEW.PRODUCT_NAME) CONTAINING 'DÂY' OR UPPER(NEW.PRODUCT_NAME) CONTAINING 'DAY' THEN 'NECKLACE'
            ELSE NULL
        END;

        IF (v_code IS NOT NULL) THEN
            SELECT FIRST 1 G.ID
            FROM FINISHED_PRODUCT_GROUPS G
            WHERE G.COMPANY_ID = NEW.COMPANY_ID AND G.CODE = :v_code AND G.IS_ACTIVE = TRUE
            INTO NEW.FINISHED_PRODUCT_GROUP_ID;
    END
END^
