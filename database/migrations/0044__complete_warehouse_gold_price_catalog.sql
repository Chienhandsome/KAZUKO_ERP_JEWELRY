KAZUKO ERP JEWELRY - DATABASE MIGRATION SCRIPT
================================================================================
Migration Version: 44
Migration Name:    COMPLETE_WAREHOUSE_GOLD_PRICE_CATALOG
Description:       Add internal warehouse rates for active stock purities that
                   are absent from the retail gold price board.
Target Database:   Firebird 5.0 (Dialect 3, UTF8)
================================================================================
*/

SET AUTODDL OFF;

CREATE EXCEPTION EX_MIGRATION_CHECK 'Migration validation error';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 44 INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Phien ban migration 44 da ton tai.';

    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 43 INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Can migration 43 truoc migration 44.';
END^
SET TERM ; ^

-- Step 6: Seed missing active warehouse purities without modifying retail rates
UPDATE WAREHOUSE_GOLD_PRICES W
SET W.IS_ACTIVE = TRUE,
    W.UPDATED_AT = CURRENT_TIMESTAMP
WHERE W.GOLD_TYPE_CODE IN ('416', '417')
  AND EXISTS (SELECT 1 FROM MATERIALS M
              WHERE M.COMPANY_ID = W.COMPANY_ID AND M.IS_ACTIVE = TRUE
                AND M.MATERIAL_TYPE = 'GOLD'
                AND (UPPER(M.PURITY_CODE) CONTAINING '417' OR UPPER(M.PURITY_CODE) CONTAINING '10K'));

UPDATE WAREHOUSE_GOLD_PRICES W
SET W.IS_ACTIVE = TRUE,
    W.UPDATED_AT = CURRENT_TIMESTAMP
WHERE W.GOLD_TYPE_CODE = 'BAC_925'
  AND EXISTS (SELECT 1 FROM MATERIALS M
              WHERE M.COMPANY_ID = W.COMPANY_ID AND M.IS_ACTIVE = TRUE
                AND M.MATERIAL_TYPE = 'GOLD' AND UPPER(M.PURITY_CODE) CONTAINING '925');

INSERT INTO WAREHOUSE_GOLD_PRICES
    (COMPANY_ID, GOLD_PRICE_ID, GOLD_TYPE_CODE, GOLD_TYPE_NAME, PURITY_RATE,
     ISSUE_PRICE_PER_CHI, IS_ACTIVE, ROW_VERSION, UPDATED_AT)
SELECT C.ID, NULL, '417', 'Vàng 417 (10K)', 0.4170,
       COALESCE((SELECT FIRST 1 G.BUY_PRICE_PER_CHI * 0.4170 / NULLIF(G.PURITY_RATE, 0)
                 FROM GOLD_PRICES G WHERE G.COMPANY_ID = C.ID AND G.CODE = '9999'), 0),
       TRUE, 0, CURRENT_TIMESTAMP
FROM COMPANIES C
WHERE C.CODE = 'KAZUKO'
  AND EXISTS (SELECT 1 FROM MATERIALS M
              WHERE M.COMPANY_ID = C.ID AND M.IS_ACTIVE = TRUE
                AND M.MATERIAL_TYPE = 'GOLD'
                AND (UPPER(M.PURITY_CODE) CONTAINING '417' OR UPPER(M.PURITY_CODE) CONTAINING '10K'))
  AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                  WHERE W.COMPANY_ID = C.ID AND W.GOLD_TYPE_CODE IN ('416', '417'));

INSERT INTO WAREHOUSE_GOLD_PRICES
    (COMPANY_ID, GOLD_PRICE_ID, GOLD_TYPE_CODE, GOLD_TYPE_NAME, PURITY_RATE,
     ISSUE_PRICE_PER_CHI, IS_ACTIVE, ROW_VERSION, UPDATED_AT)
SELECT C.ID, NULL, 'BAC_925', 'Bạc 925', 0.9250,
       COALESCE(
           (SELECT FIRST 1 G.BUY_PRICE_PER_CHI FROM GOLD_PRICES G
            WHERE G.COMPANY_ID = C.ID AND G.CODE = 'BAC_925'),
           (SELECT MAX(B.AVERAGE_COST)
            FROM STOCK_BALANCES B
            JOIN MATERIALS M ON M.ID = B.MATERIAL_ID
            WHERE M.COMPANY_ID = C.ID AND M.MATERIAL_TYPE = 'GOLD'
              AND UPPER(M.PURITY_CODE) CONTAINING '925'),
           120000),
       TRUE, 0, CURRENT_TIMESTAMP
FROM COMPANIES C
WHERE C.CODE = 'KAZUKO'
  AND EXISTS (SELECT 1 FROM MATERIALS M
              WHERE M.COMPANY_ID = C.ID AND M.IS_ACTIVE = TRUE
                AND M.MATERIAL_TYPE = 'GOLD' AND UPPER(M.PURITY_CODE) CONTAINING '925')
  AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                  WHERE W.COMPANY_ID = C.ID AND W.GOLD_TYPE_CODE = 'BAC_925');

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*)
    FROM MATERIALS M
    WHERE M.IS_ACTIVE = TRUE AND M.MATERIAL_TYPE = 'GOLD'
      AND (UPPER(M.PURITY_CODE) CONTAINING '417' OR UPPER(M.PURITY_CODE) CONTAINING '10K')
      AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                      WHERE W.COMPANY_ID = M.COMPANY_ID
                        AND W.GOLD_TYPE_CODE IN ('416', '417') AND W.IS_ACTIVE = TRUE)
    INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Con thieu gia kho cho vang 10K/417.';

    SELECT COUNT(*)
    FROM MATERIALS M
    WHERE M.IS_ACTIVE = TRUE AND M.MATERIAL_TYPE = 'GOLD'
      AND UPPER(M.PURITY_CODE) CONTAINING '925'
      AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                      WHERE W.COMPANY_ID = M.COMPANY_ID
                        AND W.GOLD_TYPE_CODE = 'BAC_925' AND W.IS_ACTIVE = TRUE)
    INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Con thieu gia kho cho bac 925.';
END^
SET TERM ; ^

DROP EXCEPTION EX_MIGRATION_CHECK;
