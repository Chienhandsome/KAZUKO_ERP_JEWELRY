/*
================================================================================
KAZUKO ERP JEWELRY - DATABASE MIGRATION SCRIPT
================================================================================
Migration Version: 50
Migration Name:    PRODUCTION_LEGACY_COLUMNS_NULLABLE
Description:       Drop NOT NULL on WinForms legacy PRODUCTION_ORDERS columns so
                   the new module can save STOCK drafts without sales-item /
                   design / BOM headers (lines live in PRODUCTION_ORDER_LINES).
Target Database:   Firebird 5.0 (Dialect 3, UTF8)

Rollback notes (manual, forward-only ledger):
  1. Preferred recovery in production is restore from pre-migration .fbk.
  2. Re-adding NOT NULL is unsafe while STOCK drafts with NULL legacy cols exist.
================================================================================
*/

SET AUTODDL OFF;

CREATE EXCEPTION EX_MIGRATION_CHECK 'Migration validation error';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 50 INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Phien ban migration 50 da ton tai.';

    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 49 INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Can migration 49 truoc migration 50.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Bang PRODUCTION_ORDERS khong ton tai.';
END^
SET TERM ; ^

