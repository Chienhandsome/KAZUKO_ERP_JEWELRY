/* Migration 84: persist empty attendance periods.
   Requires 83. Run via Invoke-KazukoMigration.ps1 for gbak and checksum ledger.
   Recovery: restore retained pre-84 backup together with the matching application build.
   Existing attendance records and payroll snapshots are never changed.
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_ATT_PERIOD_MIGRATION 'Migration 84 requires migration 83';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF (NOT EXISTS (SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=83)) THEN EXCEPTION EX_ATT_PERIOD_MIGRATION;
END^
SET TERM ; ^
CREATE TABLE HR_ATTENDANCE_PERIODS (
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID),
 PERIOD_YEAR INTEGER NOT NULL,
 PERIOD_MONTH INTEGER NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_HR_ATT_PERIODS PRIMARY KEY(COMPANY_ID,PERIOD_YEAR,PERIOD_MONTH),
 CONSTRAINT CK_HR_ATT_PERIOD_DATE CHECK(PERIOD_YEAR BETWEEN 1900 AND 9998 AND PERIOD_MONTH BETWEEN 1 AND 12)
);
-- Step 6: Seed
INSERT INTO HR_ATTENDANCE_PERIODS(COMPANY_ID,PERIOD_YEAR,PERIOD_MONTH)
SELECT DISTINCT COMPANY_ID, CAST(EXTRACT(YEAR FROM WORK_DATE) AS INTEGER), CAST(EXTRACT(MONTH FROM WORK_DATE) AS INTEGER)
FROM HR_ATTENDANCE_RECORDS;
DROP EXCEPTION EX_ATT_PERIOD_MIGRATION;
