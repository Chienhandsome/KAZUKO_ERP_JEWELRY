    CHECK (WAREHOUSE_GOLD_PRICE_PER_CHI IS NULL OR WAREHOUSE_GOLD_PRICE_PER_CHI >= 0);

ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD WAREHOUSE_GOLD_PRICE_ID BIGINT;
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD GOLD_PRICE_CODE VARCHAR(40);
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD GOLD_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD GOLD_WEIGHT_CHI NUMERIC(18,4) DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD LABOR_COST NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD NON_GOLD_COST NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD CONSTRAINT FK_FP_DOCUMENT_WGP
    FOREIGN KEY (WAREHOUSE_GOLD_PRICE_ID) REFERENCES WAREHOUSE_GOLD_PRICES (ID);
ALTER TABLE FINISHED_PRODUCT_DOCUMENT_LINES ADD CONSTRAINT CK_FP_DOCUMENT_PRICE_PARTS CHECK (
    GOLD_PRICE_PER_CHI >= 0 AND GOLD_WEIGHT_CHI >= 0 AND LABOR_COST >= 0 AND NON_GOLD_COST >= 0);

-- Step 6: Seed warehouse prices and normalize legacy product cost components
INSERT INTO WAREHOUSE_GOLD_PRICES
    (COMPANY_ID, GOLD_PRICE_ID, GOLD_TYPE_CODE, GOLD_TYPE_NAME, PURITY_RATE,
     ISSUE_PRICE_PER_CHI, IS_ACTIVE, ROW_VERSION, UPDATED_AT)
SELECT G.COMPANY_ID, G.ID, G.CODE, G.NAME, G.PURITY_RATE,
       G.BUY_PRICE_PER_CHI, G.IS_ACTIVE, 0, CURRENT_TIMESTAMP
FROM GOLD_PRICES G
WHERE NOT EXISTS (
    SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
    WHERE W.COMPANY_ID = G.COMPANY_ID AND W.GOLD_TYPE_CODE = G.CODE
);

-- Some warehouse purities may not be present on the retail board. Keep them
-- configurable here without adding rows to (or changing) the retail board.
INSERT INTO WAREHOUSE_GOLD_PRICES
    (COMPANY_ID, GOLD_PRICE_ID, GOLD_TYPE_CODE, GOLD_TYPE_NAME, PURITY_RATE,
     ISSUE_PRICE_PER_CHI, IS_ACTIVE, ROW_VERSION, UPDATED_AT)
SELECT C.ID, NULL, '916', 'Vàng 916 (22K)', 0.9160,
       COALESCE((SELECT FIRST 1 G.BUY_PRICE_PER_CHI * 0.9160 / NULLIF(G.PURITY_RATE, 0)
                 FROM GOLD_PRICES G WHERE G.COMPANY_ID = C.ID AND G.CODE = '9999'), 0),
       TRUE, 0, CURRENT_TIMESTAMP
FROM COMPANIES C
WHERE C.CODE = 'KAZUKO'
  AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                  WHERE W.COMPANY_ID = C.ID AND W.GOLD_TYPE_CODE = '916');

INSERT INTO WAREHOUSE_GOLD_PRICES
    (COMPANY_ID, GOLD_PRICE_ID, GOLD_TYPE_CODE, GOLD_TYPE_NAME, PURITY_RATE,
     ISSUE_PRICE_PER_CHI, IS_ACTIVE, ROW_VERSION, UPDATED_AT)
SELECT C.ID, NULL, '375', 'Vàng 375 (9K)', 0.3750,
       COALESCE((SELECT FIRST 1 G.BUY_PRICE_PER_CHI * 0.3750 / NULLIF(G.PURITY_RATE, 0)
                 FROM GOLD_PRICES G WHERE G.COMPANY_ID = C.ID AND G.CODE = '9999'), 0),
       TRUE, 0, CURRENT_TIMESTAMP
FROM COMPANIES C
WHERE C.CODE = 'KAZUKO'
  AND NOT EXISTS (SELECT 1 FROM WAREHOUSE_GOLD_PRICES W
                  WHERE W.COMPANY_ID = C.ID AND W.GOLD_TYPE_CODE = '375');

UPDATE FINISHED_PRODUCTS
SET GOLD_WEIGHT = TOTAL_WEIGHT,
    NON_GOLD_MATERIAL_COST = CASE
    WHEN TOTAL_COST > MATERIAL_COST + LABOR_COST
        THEN TOTAL_COST - MATERIAL_COST - LABOR_COST
    ELSE 0
END;

