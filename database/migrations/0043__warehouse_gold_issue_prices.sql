CREATE TABLE WAREHOUSE_GOLD_PRICES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    GOLD_PRICE_ID BIGINT,
    GOLD_TYPE_CODE VARCHAR(40) NOT NULL,
    GOLD_TYPE_NAME VARCHAR(200) NOT NULL,
    PURITY_RATE NUMERIC(8,4) DEFAULT 0 NOT NULL,
    ISSUE_PRICE_PER_CHI NUMERIC(18,2) DEFAULT 0 NOT NULL,
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    ROW_VERSION BIGINT DEFAULT 0 NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_WAREHOUSE_GOLD_PRICES PRIMARY KEY (ID),
    CONSTRAINT UQ_WAREHOUSE_GOLD_PRICE UNIQUE (COMPANY_ID, GOLD_TYPE_CODE),
    CONSTRAINT CK_WAREHOUSE_GOLD_PRICE CHECK (ISSUE_PRICE_PER_CHI >= 0 AND PURITY_RATE >= 0),
    CONSTRAINT FK_WGP_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_WGP_GOLD_PRICE FOREIGN KEY (GOLD_PRICE_ID) REFERENCES GOLD_PRICES (ID),
    CONSTRAINT FK_WGP_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID)
);

CREATE TABLE WAREHOUSE_GOLD_PRICE_HISTORY (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    WAREHOUSE_GOLD_PRICE_ID BIGINT NOT NULL,
    GOLD_CODE VARCHAR(40) NOT NULL,
    GOLD_NAME VARCHAR(200) NOT NULL,
    OLD_PRICE_PER_CHI NUMERIC(18,2) NOT NULL,
    NEW_PRICE_PER_CHI NUMERIC(18,2) NOT NULL,
    CHANGED_BY BIGINT,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NOTES VARCHAR(500),
    CONSTRAINT PK_WAREHOUSE_GOLD_PRICE_HISTORY PRIMARY KEY (ID),
    CONSTRAINT CK_WGPH_PRICES CHECK (OLD_PRICE_PER_CHI >= 0 AND NEW_PRICE_PER_CHI >= 0),
    CONSTRAINT FK_WGPH_PRICE FOREIGN KEY (WAREHOUSE_GOLD_PRICE_ID) REFERENCES WAREHOUSE_GOLD_PRICES (ID),
    CONSTRAINT FK_WGPH_USER FOREIGN KEY (CHANGED_BY) REFERENCES USERS (ID)
);

CREATE INDEX IX_WGPH_PRICE_DATE ON WAREHOUSE_GOLD_PRICE_HISTORY (WAREHOUSE_GOLD_PRICE_ID, CHANGED_AT);

ALTER TABLE FINISHED_PRODUCTS ADD NON_GOLD_MATERIAL_COST NUMERIC(18,2) DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCTS ADD CONSTRAINT CK_FP_NON_GOLD_COST CHECK (NON_GOLD_MATERIAL_COST >= 0);

ALTER TABLE STOCK_DOCUMENT_LINES ADD WAREHOUSE_GOLD_PRICE_ID BIGINT;
ALTER TABLE STOCK_DOCUMENT_LINES ADD WAREHOUSE_GOLD_PRICE_PER_CHI NUMERIC(18,2);
ALTER TABLE STOCK_DOCUMENT_LINES ADD CONSTRAINT FK_STOCK_LINE_WGP
    FOREIGN KEY (WAREHOUSE_GOLD_PRICE_ID) REFERENCES WAREHOUSE_GOLD_PRICES (ID);
