    WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' AND RDB$FIELD_NAME = 'ROW_VERSION'
    INTO :v_nullable;
    IF (:v_nullable = 0) THEN
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ALTER ROW_VERSION SET DEFAULT 0';
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ALTER ROW_VERSION SET NOT NULL';

    SELECT COUNT(*) FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_NAME = 'CK_PO_STATUS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ADD CONSTRAINT CK_PO_STATUS CHECK (STATUS_CODE IN (''DRAFT'', ''IN_PROGRESS'', ''COMPLETED'', ''CANCELLED''))';

