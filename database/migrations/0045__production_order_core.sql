        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ALTER ORDER_SOURCE SET NOT NULL';

    SELECT COALESCE(RDB$NULL_FLAG, 0) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' AND RDB$FIELD_NAME = 'EXECUTION_TYPE'
    INTO :v_nullable;
    IF (:v_nullable = 0) THEN
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ALTER EXECUTION_TYPE SET NOT NULL';

    SELECT COALESCE(RDB$NULL_FLAG, 0) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' AND RDB$FIELD_NAME = 'ORDER_DATE'
    INTO :v_nullable;
    IF (:v_nullable = 0) THEN
