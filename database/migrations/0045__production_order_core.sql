    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ADD CONSTRAINT CK_PO_EXECUTION CHECK ((EXECUTION_TYPE = ''OUTSOURCED'' AND EXTERNAL_WORKER_ID IS NOT NULL) OR (EXECUTION_TYPE = ''IN_HOUSE'' AND EXTERNAL_WORKER_ID IS NULL))';

