        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ALTER ORDER_DATE SET NOT NULL';
    END

    SELECT COALESCE(RDB$NULL_FLAG, 0) FROM RDB$RELATION_FIELDS
