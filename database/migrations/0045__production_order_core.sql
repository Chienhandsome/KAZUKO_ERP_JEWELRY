    IF (:v_cnt = 0) THEN
        EXECUTE STATEMENT 'ALTER TABLE PRODUCTION_ORDERS ADD CONSTRAINT CK_PO_SOURCE CHECK ((ORDER_SOURCE = ''STOCK'' AND SALES_ORDER_ID IS NULL) OR (ORDER_SOURCE = ''SALES_ORDER'' AND SALES_ORDER_ID IS NOT NULL))';

