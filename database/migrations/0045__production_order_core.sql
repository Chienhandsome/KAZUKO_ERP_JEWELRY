INSERT INTO DOCUMENT_SEQUENCES (DOCUMENT_TYPE, BRANCH_ID, YEAR_NO, LAST_NUMBER, UPDATED_AT)
SELECT 'PRODUCTION_ORDER', B.ID, EXTRACT(YEAR FROM CURRENT_DATE), 0, CURRENT_TIMESTAMP
FROM BRANCHES B
WHERE NOT EXISTS (
    SELECT 1 FROM DOCUMENT_SEQUENCES S
    WHERE S.DOCUMENT_TYPE = 'PRODUCTION_ORDER'
      AND S.BRANCH_ID = B.ID
      AND S.YEAR_NO = EXTRACT(YEAR FROM CURRENT_DATE));

