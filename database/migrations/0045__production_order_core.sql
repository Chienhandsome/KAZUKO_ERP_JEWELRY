    WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' AND RDB$FIELD_NAME = 'ORDER_SOURCE'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Thieu cot ORDER_SOURCE sau DDL.';

    SELECT FIRST 1 ID FROM LOCATIONS
    WHERE INVENTORY_SCOPE = 'RAW_MATERIAL' AND IS_ACTIVE = TRUE
    ORDER BY ID INTO :v_src_loc;
    IF (:v_src_loc IS NULL) THEN
        SELECT FIRST 1 ID FROM LOCATIONS WHERE IS_ACTIVE = TRUE ORDER BY ID INTO :v_src_loc;
    IF (:v_src_loc IS NULL) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Khong tim thay kho RAW_MATERIAL/GENERAL.';

    SELECT FIRST 1 ID FROM LOCATIONS
    WHERE INVENTORY_SCOPE = 'FINISHED_GOODS' AND IS_ACTIVE = TRUE
    ORDER BY ID INTO :v_fin_loc;
    IF (:v_fin_loc IS NULL) THEN
        SELECT FIRST 1 ID FROM LOCATIONS
        WHERE ID <> :v_src_loc AND IS_ACTIVE = TRUE
        ORDER BY ID INTO :v_fin_loc;
    IF (:v_fin_loc IS NULL) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Khong tim thay kho FINISHED_GOODS.';

    UPDATE PRODUCTION_ORDERS
       SET ORDER_SOURCE = CASE WHEN SALES_ORDER_ID IS NOT NULL THEN 'SALES_ORDER' ELSE 'STOCK' END,
           EXECUTION_TYPE = COALESCE(EXECUTION_TYPE, 'IN_HOUSE'),
           ORDER_DATE = COALESCE(ORDER_DATE, CREATED_AT, CURRENT_TIMESTAMP),
           SOURCE_LOCATION_ID = COALESCE(SOURCE_LOCATION_ID, :v_src_loc),
           FINISHED_LOCATION_ID = COALESCE(FINISHED_LOCATION_ID, :v_fin_loc),
           ROW_VERSION = COALESCE(ROW_VERSION, 0),
           COMPLETED_AT = CASE
               WHEN STATUS_CODE = 'COMPLETED' THEN COALESCE(COMPLETED_AT, UPDATED_AT, CREATED_AT, CURRENT_TIMESTAMP)
               ELSE COMPLETED_AT END,
           STATUS_CODE = CASE
               WHEN STATUS_CODE IN ('DRAFT', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED') THEN STATUS_CODE
               WHEN STATUS_CODE IN ('PLANNED', 'RELEASED') THEN 'DRAFT'
               WHEN STATUS_CODE = 'WAITING_QC' THEN 'IN_PROGRESS'
               ELSE 'DRAFT' END
     WHERE ORDER_SOURCE IS NULL
        OR EXECUTION_TYPE IS NULL
        OR ORDER_DATE IS NULL
        OR SOURCE_LOCATION_ID IS NULL
        OR FINISHED_LOCATION_ID IS NULL
        OR ROW_VERSION IS NULL
        OR STATUS_CODE NOT IN ('DRAFT', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED');

    SELECT COALESCE(RDB$NULL_FLAG, 0) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'PRODUCTION_ORDERS' AND RDB$FIELD_NAME = 'ORDER_SOURCE'
