/* Migration 85: separate distributor/manufacturer/origin for jewelry labels.
   Requires 84. Apply with Invoke-KazukoMigration.ps1 (gbak + checksum ledger).
   Recovery: restore retained pre-85 backup with the previous app build.
   Existing NAME/ADDRESS/TCCS and saved print templates are preserved.
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_LABEL_PARTIES_MIGRATION 'Migration 85 requires migration 84';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF (NOT EXISTS (SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=84)) THEN EXCEPTION EX_LABEL_PARTIES_MIGRATION;
END^
SET TERM ; ^
ALTER TABLE COMPANIES ADD DISTRIBUTOR_NAME VARCHAR(200);
ALTER TABLE COMPANIES ADD DISTRIBUTOR_ADDRESS VARCHAR(500);
ALTER TABLE COMPANIES ADD MANUFACTURER_NAME VARCHAR(200);
ALTER TABLE COMPANIES ADD MANUFACTURER_ADDRESS VARCHAR(500);
ALTER TABLE COMPANIES ADD COUNTRY_OF_ORIGIN VARCHAR(100);
-- Step 6: Seed
UPDATE COMPANIES SET DISTRIBUTOR_NAME=NAME, DISTRIBUTOR_ADDRESS=ADDRESS,
 MANUFACTURER_NAME=NAME, MANUFACTURER_ADDRESS=ADDRESS, COUNTRY_OF_ORIGIN='Vietnam';
DROP EXCEPTION EX_LABEL_PARTIES_MIGRATION;
