/* Forward-only. Order create-request snapshot permits safe retry of LSX creation
   (same pattern as 0091 for finished receipts). Restore pre-migration .fbk to roll back;
   do not drop tables with posted documents. */
SET AUTODDL OFF;
CREATE TABLE PRODUCTION_ORDER_REQUESTS (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID),
 BRANCH_ID BIGINT NOT NULL REFERENCES BRANCHES(ID),
 REQUEST_ID CHAR(36) CHARACTER SET ASCII NOT NULL,
 REQUEST_HASH CHAR(64) CHARACTER SET ASCII NOT NULL,
 ORDER_ID BIGINT NOT NULL REFERENCES PRODUCTION_ORDERS(ID),
 PAYLOAD BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT UQ_PROD_ORDER_REQUEST UNIQUE(COMPANY_ID,BRANCH_ID,REQUEST_ID),
 CONSTRAINT UQ_PROD_ORDER_ORDER UNIQUE(ORDER_ID)
);
COMMIT;
