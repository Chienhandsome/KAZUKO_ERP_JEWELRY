CREATE TABLE WORKER_GOLD_DEBTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    BRANCH_ID BIGINT NOT NULL,
    CODE VARCHAR(40) NOT NULL,
    WORKER_TYPE VARCHAR(20) NOT NULL,
    WORKER_ID BIGINT NOT NULL,
    WORKER_NAME VARCHAR(200) NOT NULL,
    GOLD_PURITY_CODE VARCHAR(30),
    WEIGHT_CHI NUMERIC(18,3) NOT NULL,
    WEIGHT_ISSUED_CHI NUMERIC(18,3) NOT NULL,
    WEIGHT_RECEIVED_CHI NUMERIC(18,3) NOT NULL,
    WEIGHT_LOSS_CHI NUMERIC(18,3) DEFAULT 0 NOT NULL,
    PRODUCTION_ORDER_ID BIGINT NOT NULL,
    PRODUCTION_ORDER_CODE VARCHAR(40) NOT NULL,
    STATUS_CODE VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
    NOTES VARCHAR(500),
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_WORKER_GOLD_DEBTS PRIMARY KEY (ID),
    CONSTRAINT FK_WGD_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_WGD_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT UQ_WGD_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT UQ_WGD_ORDER UNIQUE (COMPANY_ID, PRODUCTION_ORDER_ID),
    CONSTRAINT CK_WGD_WEIGHT_POSITIVE CHECK (WEIGHT_CHI > 0),
    CONSTRAINT CK_WGD_WORKER_TYPE CHECK (WORKER_TYPE IN ('EMPLOYEE')),
    CONSTRAINT CK_WGD_STATUS CHECK (STATUS_CODE IN ('OPEN', 'PARTIAL', 'PAID', 'CANCELLED'))
);

CREATE INDEX IX_WGD_WORKER_STATUS
    ON WORKER_GOLD_DEBTS (COMPANY_ID, WORKER_ID, STATUS_CODE);

