CREATE TABLE PRINT_TEMPLATES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    CODE VARCHAR(40) CHARACTER SET ASCII NOT NULL,
    NAME VARCHAR(200) NOT NULL,
    CONTENT BLOB SUB_TYPE 0 SEGMENT SIZE 80 NOT NULL,
    CONTENT_HASH VARCHAR(64) CHARACTER SET ASCII NOT NULL,
    NOTES VARCHAR(500),
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PRINT_TEMPLATES PRIMARY KEY (ID),
    CONSTRAINT FK_PRINT_TMPL_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_PRINT_TMPL_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_PRINT_TEMPLATES_CODE UNIQUE (COMPANY_ID, CODE)
);

CREATE INDEX IX_PRINT_TEMPLATES_CODE ON PRINT_TEMPLATES (CODE);

