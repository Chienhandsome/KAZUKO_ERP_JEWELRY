/* Migration 88, requires 87. Verified live MAX(VERSION_NO)=87 before creation.
   Apply with Invoke-KazukoMigration.ps1 after backup + restore verification.
   Existing/automatic vouchers remain unclassified; no financial amounts are changed.
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_VC_MIGRATION 'Migration 88 requires migration 87';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF (NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=87)) THEN EXCEPTION EX_VC_MIGRATION;
END^
SET TERM ; ^
CREATE TABLE VOUCHER_CATEGORIES (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 COMPANY_ID BIGINT NOT NULL,
 VOUCHER_TYPE VARCHAR(10) NOT NULL,
 CODE VARCHAR(40) CHARACTER SET ASCII NOT NULL,
 NAME VARCHAR(150) NOT NULL,
 IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
 CREATED_BY BIGINT,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UPDATED_BY BIGINT,
 UPDATED_AT TIMESTAMP,
 CONSTRAINT PK_VOUCHER_CATEGORIES PRIMARY KEY(ID),
 CONSTRAINT FK_VC_COMPANY FOREIGN KEY(COMPANY_ID) REFERENCES COMPANIES(ID),
 CONSTRAINT FK_VC_CREATED_BY FOREIGN KEY(CREATED_BY) REFERENCES USERS(ID),
 CONSTRAINT FK_VC_UPDATED_BY FOREIGN KEY(UPDATED_BY) REFERENCES USERS(ID),
 CONSTRAINT CK_VC_TYPE CHECK(VOUCHER_TYPE IN ('IN','OUT')),
 CONSTRAINT CK_VC_CODE CHECK(TRIM(CODE)<>''),
 CONSTRAINT CK_VC_NAME CHECK(TRIM(NAME)<>''),
 CONSTRAINT UQ_VC_CODE UNIQUE(COMPANY_ID,VOUCHER_TYPE,CODE),
 CONSTRAINT UQ_VC_SCOPE UNIQUE(COMPANY_ID,VOUCHER_TYPE,ID)
);
CREATE INDEX IX_VC_ACTIVE ON VOUCHER_CATEGORIES(COMPANY_ID,VOUCHER_TYPE,IS_ACTIVE);
ALTER TABLE CASH_VOUCHERS ADD CATEGORY_ID BIGINT;
ALTER TABLE CASH_VOUCHERS ADD CATEGORY_NAME VARCHAR(150);
ALTER TABLE CASH_VOUCHERS ADD CONSTRAINT FK_CV_CATEGORY
 FOREIGN KEY(COMPANY_ID,VOUCHER_TYPE,CATEGORY_ID) REFERENCES VOUCHER_CATEGORIES(COMPANY_ID,VOUCHER_TYPE,ID);
CREATE INDEX IX_CV_CATEGORY ON CASH_VOUCHERS(COMPANY_ID,CATEGORY_ID);
