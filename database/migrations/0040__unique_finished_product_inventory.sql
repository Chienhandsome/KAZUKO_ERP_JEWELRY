Migration Name:    UNIQUE_FINISHED_PRODUCT_INVENTORY
Description:       Add explicit inventory scopes, optimistic concurrency and
                   per-serial document lines for finished-product movements.
Target Database:   Firebird 5.0 (Dialect 3, UTF8)

Rollback notes (manual, forward-only ledger):
  1. Restore the pre-migration backup whenever possible.
  2. Otherwise drop FINISHED_PRODUCT_DOCUMENT_LINES, then drop the columns
     added by this migration after first exporting their data.
