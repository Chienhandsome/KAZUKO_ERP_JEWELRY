SET AUTODDL OFF;

CREATE EXCEPTION EX_MIGRATION_CHECK 'Migration validation error';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 40 INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Phien ban migration 40 da ton tai.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Bang FINISHED_PRODUCTS khong ton tai.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCT_MOVEMENTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Can migration 36 truoc migration 40.';
END^
SET TERM ; ^

ALTER TABLE LOCATIONS ADD INVENTORY_SCOPE VARCHAR(30) DEFAULT 'GENERAL' NOT NULL;
ALTER TABLE FINISHED_PRODUCTS ADD ROW_VERSION BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCT_MOVEMENTS ADD FROM_LOCATION_ID BIGINT;
ALTER TABLE FINISHED_PRODUCT_MOVEMENTS ADD TO_LOCATION_ID BIGINT;

ALTER TABLE LOCATIONS ADD CONSTRAINT CK_LOCATION_INVENTORY_SCOPE CHECK (
    INVENTORY_SCOPE IN ('GENERAL', 'RAW_MATERIAL', 'FINISHED_GOODS', 'SALES_FLOOR', 'SERVICE'));
ALTER TABLE FINISHED_PRODUCT_MOVEMENTS ADD CONSTRAINT FK_FPM_FROM_LOCATION
    FOREIGN KEY (FROM_LOCATION_ID) REFERENCES LOCATIONS (ID);
ALTER TABLE FINISHED_PRODUCT_MOVEMENTS ADD CONSTRAINT FK_FPM_TO_LOCATION
    FOREIGN KEY (TO_LOCATION_ID) REFERENCES LOCATIONS (ID);

CREATE TABLE FINISHED_PRODUCT_DOCUMENT_LINES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DOCUMENT_ID BIGINT NOT NULL,
    LINE_NUMBER INTEGER NOT NULL,
    FINISHED_PRODUCT_ID BIGINT NOT NULL,
    SOURCE_LOCATION_ID BIGINT,
    DESTINATION_LOCATION_ID BIGINT,
    STATUS_BEFORE VARCHAR(30) NOT NULL,
    STATUS_AFTER VARCHAR(30) NOT NULL,
    UNIT_COST NUMERIC(18,2) DEFAULT 0 NOT NULL,
    NOTES VARCHAR(500),
    CONSTRAINT PK_FP_DOCUMENT_LINES PRIMARY KEY (ID),
    CONSTRAINT UQ_FP_DOCUMENT_LINE_NO UNIQUE (DOCUMENT_ID, LINE_NUMBER),
    CONSTRAINT UQ_FP_DOCUMENT_ITEM UNIQUE (DOCUMENT_ID, FINISHED_PRODUCT_ID),
    CONSTRAINT CK_FP_DOCUMENT_COST CHECK (UNIT_COST >= 0),
    CONSTRAINT FK_FP_DOCUMENT FOREIGN KEY (DOCUMENT_ID) REFERENCES STOCK_DOCUMENTS (ID),
    CONSTRAINT FK_FP_DOCUMENT_PRODUCT FOREIGN KEY (FINISHED_PRODUCT_ID) REFERENCES FINISHED_PRODUCTS (ID),
    CONSTRAINT FK_FP_DOCUMENT_SOURCE FOREIGN KEY (SOURCE_LOCATION_ID) REFERENCES LOCATIONS (ID),
    CONSTRAINT FK_FP_DOCUMENT_DEST FOREIGN KEY (DESTINATION_LOCATION_ID) REFERENCES LOCATIONS (ID)
);

CREATE INDEX IX_FP_DOCUMENT_PRODUCT ON FINISHED_PRODUCT_DOCUMENT_LINES (FINISHED_PRODUCT_ID);

-- Step 6: Seed and normalize legacy inventory data
UPDATE LOCATIONS
SET INVENTORY_SCOPE = CASE
    WHEN CODE IN ('KHO_THANH_PHAM', 'QUAY_TRUNG_TAM') THEN 'FINISHED_GOODS'
    WHEN CODE IN ('KHO_TRUNG_TAM', 'KHO_THU_HOI') THEN 'RAW_MATERIAL'
    ELSE INVENTORY_SCOPE
END;

UPDATE OR INSERT INTO LOCATIONS (BRANCH_ID, CODE, NAME, LOCATION_TYPE, INVENTORY_SCOPE, IS_ACTIVE)
VALUES ((SELECT FIRST 1 ID FROM BRANCHES WHERE IS_ACTIVE = TRUE ORDER BY ID),
        'KHO_BAN_HANG', 'Kho bán hàng', 'WAREHOUSE', 'SALES_FLOOR', TRUE)
MATCHING (CODE);

UPDATE FINISHED_PRODUCTS F
SET LOCATION_ID = (SELECT FIRST 1 L.ID FROM LOCATIONS L
                   WHERE L.BRANCH_ID = F.BRANCH_ID AND L.INVENTORY_SCOPE = 'SALES_FLOOR'
                   ORDER BY L.ID)
WHERE F.STATUS_CODE = 'DISPLAYED';

UPDATE FINISHED_PRODUCTS
SET LOCATION_ID = NULL
WHERE STATUS_CODE = 'SOLD';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'LOCATIONS' AND RDB$FIELD_NAME = 'INVENTORY_SCOPE'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'LOCATIONS thieu INVENTORY_SCOPE.';

    SELECT COUNT(*) FROM RDB$RELATIONS
    WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCT_DOCUMENT_LINES'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Khong tao duoc FINISHED_PRODUCT_DOCUMENT_LINES.';
END^
SET TERM ; ^

DROP EXCEPTION EX_MIGRATION_CHECK;
