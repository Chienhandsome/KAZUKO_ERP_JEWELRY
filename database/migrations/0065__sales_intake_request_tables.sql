/*
================================================================================
KAZUKO ERP JEWELRY - DATABASE MIGRATION SCRIPT
================================================================================
Migration Version: 65
Migration Name:    SALES_INTAKE_REQUEST_TABLES
Description:       Pending TP→BH requests live outside STOCK_DOCUMENTS.
                   Transfer voucher is created only when BH approves.
                   Cleans accidental DRAFT FINISHED_TO_SALES stock docs
                   from migration 64 interim flow (no movements).
Target Database:   Firebird 5.0 (Dialect 3, UTF8)
================================================================================
Rollback (dev):
  DROP TABLE SALES_INTAKE_REQUEST_LINES;
  DROP TABLE SALES_INTAKE_REQUESTS;
  DELETE FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 65;
================================================================================
*/

SET AUTODDL OFF;

CREATE EXCEPTION EX_MIGRATION_CHECK 'Migration validation error';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 65 INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Phien ban migration 65 da ton tai.';

    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 64 INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Can migration 64 truoc migration 65.';
END^
SET TERM ; ^

/* ---- Remove draft transfer vouchers created before approval (interim) ---- */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
    DELETE FROM FINISHED_PRODUCT_DOCUMENT_LINES L
    WHERE EXISTS (
        SELECT 1 FROM STOCK_DOCUMENTS D
        WHERE D.ID = L.DOCUMENT_ID
          AND D.DOCUMENT_TYPE = 'TRANSFER'
          AND D.PURPOSE_CODE = 'FINISHED_TO_SALES'
          AND D.STATUS_CODE = 'DRAFT'
          AND NOT EXISTS (
              SELECT 1 FROM FINISHED_PRODUCT_MOVEMENTS M
              WHERE M.DOCUMENT_TYPE = 'TRANSFER' AND M.DOCUMENT_ID = D.ID));

    DELETE FROM STOCK_DOCUMENTS D
    WHERE D.DOCUMENT_TYPE = 'TRANSFER'
      AND D.PURPOSE_CODE = 'FINISHED_TO_SALES'
      AND D.STATUS_CODE = 'DRAFT'
      AND NOT EXISTS (
          SELECT 1 FROM FINISHED_PRODUCT_MOVEMENTS M
          WHERE M.DOCUMENT_TYPE = 'TRANSFER' AND M.DOCUMENT_ID = D.ID)
      AND NOT EXISTS (
          SELECT 1 FROM FINISHED_PRODUCT_DOCUMENT_LINES L
          WHERE L.DOCUMENT_ID = D.ID);
END^
SET TERM ; ^

CREATE TABLE SALES_INTAKE_REQUESTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    BRANCH_ID BIGINT NOT NULL,
    CODE VARCHAR(40) NOT NULL,
    REQUEST_DATE TIMESTAMP NOT NULL,
    SOURCE_LOCATION_ID BIGINT NOT NULL,
    DESTINATION_LOCATION_ID BIGINT NOT NULL,
    STATUS_CODE VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    NOTES VARCHAR(1000),
    REJECTION_REASON VARCHAR(500),
    STOCK_DOCUMENT_ID BIGINT,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DECIDED_BY BIGINT,
    DECIDED_AT TIMESTAMP,
    CONSTRAINT PK_SALES_INTAKE_REQUESTS PRIMARY KEY (ID),
    CONSTRAINT UQ_SALES_INTAKE_REQ_CODE UNIQUE (COMPANY_ID, BRANCH_ID, CODE),
    CONSTRAINT FK_SIR_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_SIR_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT FK_SIR_SOURCE FOREIGN KEY (SOURCE_LOCATION_ID) REFERENCES LOCATIONS (ID),
    CONSTRAINT FK_SIR_DEST FOREIGN KEY (DESTINATION_LOCATION_ID) REFERENCES LOCATIONS (ID),
    CONSTRAINT FK_SIR_STOCK_DOC FOREIGN KEY (STOCK_DOCUMENT_ID) REFERENCES STOCK_DOCUMENTS (ID),
    CONSTRAINT FK_SIR_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_SIR_DECIDED_BY FOREIGN KEY (DECIDED_BY) REFERENCES USERS (ID),
    CONSTRAINT CK_SIR_STATUS CHECK (STATUS_CODE IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX IX_SIR_BRANCH_STATUS ON SALES_INTAKE_REQUESTS (BRANCH_ID, STATUS_CODE, CREATED_AT);
CREATE INDEX IX_SIR_STOCK_DOC ON SALES_INTAKE_REQUESTS (STOCK_DOCUMENT_ID);

CREATE TABLE SALES_INTAKE_REQUEST_LINES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    REQUEST_ID BIGINT NOT NULL,
    LINE_NUMBER INTEGER NOT NULL,
    FINISHED_PRODUCT_ID BIGINT NOT NULL,
    UNIT_COST NUMERIC(18,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SALES_INTAKE_REQ_LINES PRIMARY KEY (ID),
    CONSTRAINT UQ_SIR_LINE_NO UNIQUE (REQUEST_ID, LINE_NUMBER),
    CONSTRAINT UQ_SIR_LINE_PRODUCT UNIQUE (REQUEST_ID, FINISHED_PRODUCT_ID),
    CONSTRAINT FK_SIRL_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES SALES_INTAKE_REQUESTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_SIRL_PRODUCT FOREIGN KEY (FINISHED_PRODUCT_ID) REFERENCES FINISHED_PRODUCTS (ID),
    CONSTRAINT CK_SIRL_COST CHECK (UNIT_COST >= 0),
    CONSTRAINT CK_SIRL_LINE_NO CHECK (LINE_NUMBER > 0)
);

CREATE INDEX IX_SIRL_PRODUCT ON SALES_INTAKE_REQUEST_LINES (FINISHED_PRODUCT_ID);

SET TERM ^ ;
EXECUTE BLOCK AS
