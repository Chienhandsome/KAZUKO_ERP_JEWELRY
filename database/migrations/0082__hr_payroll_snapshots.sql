/* Migration 82: payroll snapshots and separate payroll/reopen permissions.
   Requires 81. Run via Invoke-KazukoMigration.ps1 for SHA-256 ledger and gbak.
   Recovery: restore pre-82 backup with the matching application build.
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_PAYROLL_MIGRATION 'Migration 82 requires migration 81';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF (NOT EXISTS (SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=81)) THEN EXCEPTION EX_PAYROLL_MIGRATION;
END^
SET TERM ; ^
CREATE TABLE HR_PAYROLL_PERIODS (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID),
 PAY_YEAR INTEGER NOT NULL, PAY_MONTH INTEGER NOT NULL,
 STATUS VARCHAR(10) DEFAULT 'DRAFT' NOT NULL, REVISION INTEGER DEFAULT 1 NOT NULL,
 SHIFTS_PER_DAY INTEGER NOT NULL, INCLUDE_PAID_LEAVE BOOLEAN NOT NULL,
 INPUT_HASH VARCHAR(64) NOT NULL,
 CREATED_BY BIGINT NOT NULL REFERENCES USERS(ID), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CLOSED_BY BIGINT REFERENCES USERS(ID), CLOSED_AT TIMESTAMP,
 CONSTRAINT UQ_HR_PAYROLL_PERIOD UNIQUE(COMPANY_ID,PAY_YEAR,PAY_MONTH),
 CONSTRAINT CK_HR_PAYROLL_DATE CHECK(PAY_YEAR BETWEEN 1900 AND 9998 AND PAY_MONTH BETWEEN 1 AND 12),
 CONSTRAINT CK_HR_PAYROLL_STATUS CHECK(STATUS IN ('DRAFT','CLOSED')),
 CONSTRAINT CK_HR_PAYROLL_SHIFTS CHECK(SHIFTS_PER_DAY BETWEEN 1 AND 24)
);
CREATE TABLE HR_PAYROLL_LINES (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 PERIOD_ID BIGINT NOT NULL REFERENCES HR_PAYROLL_PERIODS(ID),
 EMPLOYEE_ID BIGINT NOT NULL REFERENCES HR_EMPLOYEES(ID),
 CODE VARCHAR(50) NOT NULL, FULL_NAME VARCHAR(200) NOT NULL, SALARY_METHOD VARCHAR(30) NOT NULL,
 STANDARD_UNITS NUMERIC(18,2) NOT NULL, ACTUAL_UNITS NUMERIC(18,2) NOT NULL,
 RATE NUMERIC(18,2) NOT NULL, SALARY NUMERIC(18,2) NOT NULL,
 BONUS NUMERIC(18,2) DEFAULT 0 NOT NULL, BONUS_NOTE VARCHAR(500) DEFAULT '' NOT NULL,
 DEDUCTION NUMERIC(18,2) DEFAULT 0 NOT NULL, DEDUCTION_NOTE VARCHAR(500) DEFAULT '' NOT NULL,
 WARNING VARCHAR(500) DEFAULT '' NOT NULL, SNAPSHOT_JSON BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
 CONSTRAINT UQ_HR_PAYROLL_EMPLOYEE UNIQUE(PERIOD_ID,EMPLOYEE_ID),
 CONSTRAINT CK_HR_PAYROLL_AMOUNT CHECK(SALARY>=0 AND BONUS>=0 AND DEDUCTION>=0 AND SALARY+BONUS>=DEDUCTION),
 CONSTRAINT CK_HR_PAYROLL_UNITS CHECK(STANDARD_UNITS>0 AND ACTUAL_UNITS>=0)
);
-- Step 6: Seed
INSERT INTO GROUP_PERMISSIONS (COMPANY_ID,GROUP_ID,FUNCTION_CODE,CAN_VIEW,CAN_ADD,CAN_EDIT,CAN_DELETE,IS_LOCKED)
SELECT G.COMPANY_ID,G.ID,F.CODE,
 CASE WHEN G.CODE='ADMIN' THEN TRUE ELSE FALSE END,
 CASE WHEN G.CODE='ADMIN' THEN TRUE ELSE FALSE END,
 CASE WHEN G.CODE='ADMIN' THEN TRUE ELSE FALSE END,FALSE,FALSE
FROM USER_GROUPS G CROSS JOIN (
 SELECT CAST('HR_PAYROLL' AS VARCHAR(60)) CODE FROM RDB$DATABASE UNION ALL
 SELECT 'HR_PAYROLL_REOPEN' FROM RDB$DATABASE
) F WHERE NOT EXISTS(SELECT 1 FROM GROUP_PERMISSIONS P WHERE P.GROUP_ID=G.ID AND P.FUNCTION_CODE=F.CODE);
DROP EXCEPTION EX_PAYROLL_MIGRATION;
