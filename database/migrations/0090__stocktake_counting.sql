/* Live MAX(VERSION_NO)=89 verified before naming. Preserve legacy STOCKTAKES/STOCKTAKE_LINES.
   Phase 2 only records counts; never changes inventory or posts adjustments. */
SET AUTODDL OFF;
CREATE EXCEPTION EX_COUNT_SCHEMA 'Stocktake counting requires schema 89';
SET TERM ^ ;
EXECUTE BLOCK AS BEGIN
 IF (NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=89)) THEN EXCEPTION EX_COUNT_SCHEMA;
END^
SET TERM ; ^
ALTER TABLE LOCATIONS ADD COUNT_REV BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE STOCK_BALANCES ADD COUNT_TOKEN BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE FINISHED_PRODUCTS ADD COUNT_TOKEN BIGINT DEFAULT 0 NOT NULL;
CREATE TABLE INV_COUNTS (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COMPANY_ID BIGINT NOT NULL REFERENCES COMPANIES(ID),
 BRANCH_ID BIGINT NOT NULL REFERENCES BRANCHES(ID),
 LOCATION_ID BIGINT NOT NULL REFERENCES LOCATIONS(ID),
 CODE VARCHAR(50) CHARACTER SET ASCII NOT NULL,
 COUNT_DATE DATE NOT NULL, SCOPE_CODE VARCHAR(20) CHARACTER SET ASCII NOT NULL,
 STATUS_CODE VARCHAR(20) CHARACTER SET ASCII DEFAULT 'DRAFT' NOT NULL,
 REVISION INTEGER DEFAULT 1 NOT NULL, INVENTORY_REV BIGINT NOT NULL,
 REQUEST_ID CHAR(36) CHARACTER SET ASCII NOT NULL,
 NOTES VARCHAR(1000) DEFAULT '' NOT NULL, INITIAL_SNAPSHOT BLOB SUB_TYPE TEXT,
 CREATED_BY BIGINT NOT NULL REFERENCES USERS(ID), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UPDATED_BY BIGINT REFERENCES USERS(ID), UPDATED_AT TIMESTAMP,
 CLOSED_BY BIGINT REFERENCES USERS(ID), CLOSED_AT TIMESTAMP,
 CONSTRAINT UQ_INV_COUNT_CODE UNIQUE(COMPANY_ID,CODE),
 CONSTRAINT UQ_INV_COUNT_REQUEST UNIQUE(COMPANY_ID,REQUEST_ID),
 CONSTRAINT CK_INV_COUNT_STATUS CHECK(STATUS_CODE IN ('DRAFT','COUNTED')),
 CONSTRAINT CK_INV_COUNT_SCOPE CHECK(SCOPE_CODE IN ('MATERIALS','FINISHED'))
);
CREATE TABLE INV_COUNT_LINES (
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COUNT_ID BIGINT NOT NULL REFERENCES INV_COUNTS(ID),
 ITEM_KEY VARCHAR(100) CHARACTER SET ASCII NOT NULL,
 KIND VARCHAR(20) CHARACTER SET ASCII NOT NULL, ITEM_ID BIGINT,
 ITEM_CODE VARCHAR(500) NOT NULL, ITEM_NAME VARCHAR(250) NOT NULL, UNIT_CODE VARCHAR(30) NOT NULL,
 SYSTEM_QTY NUMERIC(18,4) NOT NULL, COUNTED_QTY NUMERIC(18,4),
 NOTES VARCHAR(500) DEFAULT '' NOT NULL, STAMP VARCHAR(64) CHARACTER SET ASCII NOT NULL,
 ITEM_STATE VARCHAR(100) DEFAULT '' NOT NULL,
 NEEDS_RECOUNT BOOLEAN DEFAULT FALSE NOT NULL,
 CONSTRAINT UQ_INV_COUNT_ITEM UNIQUE(COUNT_ID,ITEM_KEY),
 CONSTRAINT CK_INV_COUNT_KIND CHECK(KIND IN ('MATERIAL','SERIAL','UNKNOWN')),
 CONSTRAINT CK_INV_COUNT_QTY CHECK(SYSTEM_QTY>=0 AND (COUNTED_QTY IS NULL OR COUNTED_QTY>=0)),
 CONSTRAINT CK_INV_COUNT_SERIAL CHECK(KIND='MATERIAL' OR (SYSTEM_QTY IN (0,1) AND (COUNTED_QTY IS NULL OR COUNTED_QTY IN (0,1)))),
 CONSTRAINT CK_INV_COUNT_ID CHECK((KIND='UNKNOWN' AND ITEM_ID IS NULL) OR (KIND IN ('MATERIAL','SERIAL') AND ITEM_ID IS NOT NULL))
);
CREATE INDEX IX_INV_COUNT_BRANCH ON INV_COUNTS(COMPANY_ID,BRANCH_ID,COUNT_DATE);
SET TERM ^ ;
CREATE TRIGGER BU_COUNT_BAL_TOKEN FOR STOCK_BALANCES ACTIVE BEFORE UPDATE POSITION 100 AS
BEGIN NEW.COUNT_TOKEN=OLD.COUNT_TOKEN+1; END^
CREATE TRIGGER BU_COUNT_FP_TOKEN FOR FINISHED_PRODUCTS ACTIVE BEFORE UPDATE POSITION 100 AS
BEGIN NEW.COUNT_TOKEN=OLD.COUNT_TOKEN+1; END^
CREATE TRIGGER AU_ID_COUNT_BAL FOR STOCK_BALANCES ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100 AS
BEGIN
 IF (INSERTING OR UPDATING) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=NEW.LOCATION_ID;
 IF (DELETING) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=OLD.LOCATION_ID;
 IF (UPDATING AND OLD.LOCATION_ID<>NEW.LOCATION_ID) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=OLD.LOCATION_ID;
END^
CREATE TRIGGER AU_ID_COUNT_FP FOR FINISHED_PRODUCTS ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 100 AS
BEGIN
 IF (INSERTING OR UPDATING) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=NEW.LOCATION_ID;
 IF (DELETING) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=OLD.LOCATION_ID;
 IF (UPDATING AND OLD.LOCATION_ID IS DISTINCT FROM NEW.LOCATION_ID) THEN UPDATE LOCATIONS SET COUNT_REV=COUNT_REV+1 WHERE ID=OLD.LOCATION_ID;
END^
SET TERM ; ^
