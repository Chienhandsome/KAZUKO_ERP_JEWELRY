DECLARE VARIABLE v_cnt INTEGER;
DECLARE VARIABLE v_gold_bad INTEGER;
BEGIN
    SELECT COUNT(*) FROM UNIT_CONVERSION_RUNS INTO :v_cnt;
    IF (:v_cnt < 1) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Thieu UNIT_CONVERSION_RUNS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'UNIT_CONVERSION_AUDIT' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Thieu UNIT_CONVERSION_AUDIT.';

    SELECT COUNT(*) FROM MATERIALS
     WHERE MATERIAL_TYPE = 'GOLD'
       AND UPPER(TRIM(UNIT_CODE)) NOT IN ('CHI')
       AND ID NOT IN (
           SELECT MATERIAL_ID FROM UNIT_CONVERSION_EXCEPTIONS
            WHERE MATERIAL_ID IS NOT NULL AND ENTITY_NAME = 'MATERIALS')
      INTO :v_gold_bad;
    IF (:v_gold_bad > 0) THEN
        EXCEPTION EX_MIGRATION_CHECK 'Con vat tu GOLD chua ve CHI va khong nam trong exceptions.';
END^
SET TERM ; ^

