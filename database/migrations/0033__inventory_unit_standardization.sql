CREATE TABLE UNIT_CONVERSION_RUNS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    STARTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    NOTES VARCHAR(500),
    CONSTRAINT PK_UNIT_CONVERSION_RUNS PRIMARY KEY (ID)
);

CREATE TABLE UNIT_CONVERSION_AUDIT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RUN_ID BIGINT NOT NULL,
    ENTITY_NAME VARCHAR(60) NOT NULL,
    ENTITY_ID BIGINT NOT NULL,
    MATERIAL_ID BIGINT,
    OLD_UNIT_CODE VARCHAR(40),
    NEW_UNIT_CODE VARCHAR(40),
    CONVERSION_FACTOR NUMERIC(18,8) NOT NULL,
    QUANTITY_BEFORE NUMERIC(18,6),
    QUANTITY_AFTER NUMERIC(18,6),
    COST_BEFORE NUMERIC(18,6),
    COST_AFTER NUMERIC(18,6),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_UNIT_CONVERSION_AUDIT PRIMARY KEY (ID),
    CONSTRAINT FK_UNIT_CONV_AUDIT_RUN FOREIGN KEY (RUN_ID) REFERENCES UNIT_CONVERSION_RUNS (ID)
);

CREATE INDEX IX_UNIT_CONV_AUDIT_RUN ON UNIT_CONVERSION_AUDIT (RUN_ID);
CREATE INDEX IX_UNIT_CONV_AUDIT_ENTITY ON UNIT_CONVERSION_AUDIT (ENTITY_NAME, ENTITY_ID);

CREATE TABLE UNIT_CONVERSION_EXCEPTIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    RUN_ID BIGINT NOT NULL,
    ENTITY_NAME VARCHAR(60) NOT NULL,
    ENTITY_ID BIGINT NOT NULL,
    MATERIAL_ID BIGINT,
    MATERIAL_TYPE VARCHAR(20),
    OLD_UNIT_CODE VARCHAR(40),
    REASON_CODE VARCHAR(60) NOT NULL,
    DETAIL_NOTE VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_UNIT_CONVERSION_EXCEPTIONS PRIMARY KEY (ID),
    CONSTRAINT FK_UNIT_CONV_EXC_RUN FOREIGN KEY (RUN_ID) REFERENCES UNIT_CONVERSION_RUNS (ID)
);

CREATE INDEX IX_UNIT_CONV_EXC_RUN ON UNIT_CONVERSION_EXCEPTIONS (RUN_ID);

-- Step 6: Seed
-- Unit conversion data rewrite (requires DDL committed by migration runner)

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_run_id BIGINT;
DECLARE VARIABLE v_mat_id BIGINT;
DECLARE VARIABLE v_mat_type VARCHAR(20);
DECLARE VARIABLE v_old_unit VARCHAR(40);
DECLARE VARIABLE v_new_unit VARCHAR(40);
DECLARE VARIABLE v_factor NUMERIC(18,8);
DECLARE VARIABLE v_ref_cost NUMERIC(18,6);
DECLARE VARIABLE v_new_cost NUMERIC(18,6);
DECLARE VARIABLE v_norm VARCHAR(40);
DECLARE VARIABLE v_bal_loc BIGINT;
DECLARE VARIABLE v_bal_qty NUMERIC(18,6);
DECLARE VARIABLE v_bal_cost NUMERIC(18,6);
DECLARE VARIABLE v_line_id BIGINT;
DECLARE VARIABLE v_line_qty NUMERIC(18,6);
DECLARE VARIABLE v_line_cost NUMERIC(18,6);
DECLARE VARIABLE v_line_amt NUMERIC(18,6);
DECLARE VARIABLE v_mov_id BIGINT;
DECLARE VARIABLE v_mov_qty NUMERIC(18,6);
DECLARE VARIABLE v_mov_cost NUMERIC(18,6);
DECLARE VARIABLE v_plan_id BIGINT;
DECLARE VARIABLE v_plan_qty NUMERIC(18,6);
DECLARE VARIABLE v_plan_net NUMERIC(18,6);
DECLARE VARIABLE v_plan_cost NUMERIC(18,6);
DECLARE VARIABLE v_plan_unit VARCHAR(40);
BEGIN
    INSERT INTO UNIT_CONVERSION_RUNS (NOTES)
    VALUES ('0033 inventory unit standardization')
    RETURNING ID INTO :v_run_id;

    FOR SELECT M.ID, M.MATERIAL_TYPE, COALESCE(M.UNIT_CODE, ''), COALESCE(M.REFERENCE_COST, 0)
        FROM MATERIALS M
        INTO :v_mat_id, :v_mat_type, :v_old_unit, :v_ref_cost
    DO
    BEGIN
        /* Map known labels (including Vietnamese diacritics in sample data) */
        v_norm = UPPER(TRIM(:v_old_unit));
        IF (:v_norm IN ('G', 'GRAM', 'GR', 'GRAMS')) THEN
            v_norm = 'GRAM';
        ELSE IF (:v_norm IN ('CHI', 'CHỈ', 'CH')
                 OR LOWER(TRIM(:v_old_unit)) IN ('chi', 'chỉ')) THEN
            v_norm = 'CHI';
        ELSE IF (:v_norm STARTING WITH 'LUONG' OR :v_norm STARTING WITH 'LƯỢNG'
                 OR :v_norm STARTING WITH 'CAY' OR :v_norm STARTING WITH 'CÂY') THEN
            v_norm = 'LUONG';
        ELSE IF (:v_norm IN ('VIEN', 'VIÊN', 'PCS', 'PC')
                 OR LOWER(TRIM(:v_old_unit)) IN ('viên', 'vien')) THEN
            v_norm = 'VIEN';
        ELSE IF (:v_norm IN ('CARAT', 'CT', 'KT') OR :v_norm STARTING WITH 'CARAT') THEN
            v_norm = 'CARAT';
        ELSE IF (:v_norm IN ('CAI', 'CÁI', 'BO', 'BỘ', 'SET')
                 OR LOWER(TRIM(:v_old_unit)) IN ('cái', 'cai')) THEN
            v_norm = 'CAI';
        ELSE IF (TRIM(:v_old_unit) = '' OR :v_old_unit IS NULL) THEN
            v_norm = '';
        ELSE
            v_norm = 'UNKNOWN';

        v_new_unit = NULL;
        v_factor = NULL;

        IF (:v_mat_type = 'GOLD') THEN
        BEGIN
            IF (:v_norm = 'CHI') THEN
            BEGIN
                v_new_unit = 'CHI';
                v_factor = 1;
            END
            ELSE IF (:v_norm = 'GRAM') THEN
            BEGIN
                v_new_unit = 'CHI';
                v_factor = CAST(1 AS NUMERIC(18,8)) / 3.75;
            END
            ELSE IF (:v_norm = 'LUONG') THEN
            BEGIN
                v_new_unit = 'CHI';
                v_factor = 10;
            END
            ELSE
            BEGIN
                INSERT INTO UNIT_CONVERSION_EXCEPTIONS
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, MATERIAL_TYPE, OLD_UNIT_CODE, REASON_CODE, DETAIL_NOTE)
                VALUES
                    (:v_run_id, 'MATERIALS', :v_mat_id, :v_mat_id, :v_mat_type, :v_old_unit,
                     'UNMAPPED_GOLD_UNIT', 'Khong xac dinh duoc he so quy doi vang');
            END
        END
        ELSE IF (:v_mat_type = 'STONE') THEN
        BEGIN
            IF (:v_norm = 'VIEN' OR :v_norm = 'CARAT') THEN
            BEGIN
                v_new_unit = :v_norm;
                v_factor = 1;
            END
            ELSE
            BEGIN
                INSERT INTO UNIT_CONVERSION_EXCEPTIONS
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, MATERIAL_TYPE, OLD_UNIT_CODE, REASON_CODE, DETAIL_NOTE)
                VALUES
                    (:v_run_id, 'MATERIALS', :v_mat_id, :v_mat_id, :v_mat_type, :v_old_unit,
                     'UNMAPPED_STONE_UNIT', 'Giu nguyen; can xac minh thu cong');
            END
        END
        ELSE IF (:v_mat_type = 'ACCESSORY') THEN
        BEGIN
            IF (:v_norm = 'CAI' OR :v_norm = 'GRAM') THEN
            BEGIN
                v_new_unit = :v_norm;
                v_factor = 1;
            END
            ELSE
            BEGIN
                INSERT INTO UNIT_CONVERSION_EXCEPTIONS
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, MATERIAL_TYPE, OLD_UNIT_CODE, REASON_CODE, DETAIL_NOTE)
                VALUES
                    (:v_run_id, 'MATERIALS', :v_mat_id, :v_mat_id, :v_mat_type, :v_old_unit,
                     'UNMAPPED_ACCESSORY_UNIT', 'Giu nguyen; can xac minh thu cong');
            END
        END
        ELSE
        BEGIN
            INSERT INTO UNIT_CONVERSION_EXCEPTIONS
                (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, MATERIAL_TYPE, OLD_UNIT_CODE, REASON_CODE, DETAIL_NOTE)
            VALUES
                (:v_run_id, 'MATERIALS', :v_mat_id, :v_mat_id, :v_mat_type, :v_old_unit,
                 'UNKNOWN_MATERIAL_TYPE', 'Nhom vat tu khong nam trong GOLD/STONE/ACCESSORY');
        END

        IF (:v_new_unit IS NOT NULL AND :v_factor IS NOT NULL) THEN
        BEGIN
            IF (:v_factor = 0) THEN
                v_new_cost = :v_ref_cost;
            ELSE
                v_new_cost = :v_ref_cost / :v_factor;

            INSERT INTO UNIT_CONVERSION_AUDIT
                (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, OLD_UNIT_CODE, NEW_UNIT_CODE,
                 CONVERSION_FACTOR, QUANTITY_BEFORE, QUANTITY_AFTER, COST_BEFORE, COST_AFTER)
            VALUES
                (:v_run_id, 'MATERIALS', :v_mat_id, :v_mat_id, :v_old_unit, :v_new_unit,
                 :v_factor, NULL, NULL, :v_ref_cost, :v_new_cost);

            UPDATE MATERIALS
               SET UNIT_CODE = :v_new_unit,
                   REFERENCE_COST = :v_new_cost,
                   UPDATED_AT = CURRENT_TIMESTAMP
             WHERE ID = :v_mat_id;

            FOR SELECT LOCATION_ID, QUANTITY, AVERAGE_COST
                FROM STOCK_BALANCES
                WHERE MATERIAL_ID = :v_mat_id
                INTO :v_bal_loc, :v_bal_qty, :v_bal_cost
            DO
            BEGIN
                INSERT INTO UNIT_CONVERSION_AUDIT
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, OLD_UNIT_CODE, NEW_UNIT_CODE,
                     CONVERSION_FACTOR, QUANTITY_BEFORE, QUANTITY_AFTER, COST_BEFORE, COST_AFTER)
                VALUES
                    (:v_run_id, 'STOCK_BALANCES', :v_mat_id, :v_mat_id, :v_old_unit, :v_new_unit,
                     :v_factor, :v_bal_qty, :v_bal_qty * :v_factor, :v_bal_cost,
                     CASE WHEN :v_factor = 0 THEN :v_bal_cost ELSE :v_bal_cost / :v_factor END);

                UPDATE STOCK_BALANCES
                   SET QUANTITY = QUANTITY * :v_factor,
                       AVERAGE_COST = CASE WHEN :v_factor = 0 THEN AVERAGE_COST ELSE AVERAGE_COST / :v_factor END,
                       UPDATED_AT = CURRENT_TIMESTAMP
                 WHERE MATERIAL_ID = :v_mat_id AND LOCATION_ID = :v_bal_loc;
            END

            FOR SELECT L.ID, L.QUANTITY, L.UNIT_COST
                FROM STOCK_DOCUMENT_LINES L
                WHERE L.MATERIAL_ID = :v_mat_id
                INTO :v_line_id, :v_line_qty, :v_line_cost
            DO
            BEGIN
                INSERT INTO UNIT_CONVERSION_AUDIT
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, OLD_UNIT_CODE, NEW_UNIT_CODE,
                     CONVERSION_FACTOR, QUANTITY_BEFORE, QUANTITY_AFTER, COST_BEFORE, COST_AFTER)
                VALUES
                    (:v_run_id, 'STOCK_DOCUMENT_LINES', :v_line_id, :v_mat_id, :v_old_unit, :v_new_unit,
                     :v_factor, :v_line_qty, :v_line_qty * :v_factor, :v_line_cost,
                     CASE WHEN :v_factor = 0 THEN :v_line_cost ELSE :v_line_cost / :v_factor END);

                UPDATE STOCK_DOCUMENT_LINES
                   SET QUANTITY = QUANTITY * :v_factor,
                       UNIT_COST = CASE WHEN :v_factor = 0 THEN UNIT_COST ELSE UNIT_COST / :v_factor END
                       /* LINE_AMOUNT kept: qty*cost invariant when both scaled */
                 WHERE ID = :v_line_id;
            END

            FOR SELECT X.ID, X.QUANTITY_CHANGE, X.UNIT_COST
                FROM STOCK_MOVEMENTS X
                WHERE X.MATERIAL_ID = :v_mat_id
                INTO :v_mov_id, :v_mov_qty, :v_mov_cost
            DO
            BEGIN
                INSERT INTO UNIT_CONVERSION_AUDIT
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, OLD_UNIT_CODE, NEW_UNIT_CODE,
                     CONVERSION_FACTOR, QUANTITY_BEFORE, QUANTITY_AFTER, COST_BEFORE, COST_AFTER)
                VALUES
                    (:v_run_id, 'STOCK_MOVEMENTS', :v_mov_id, :v_mat_id, :v_old_unit, :v_new_unit,
                     :v_factor, :v_mov_qty, :v_mov_qty * :v_factor, :v_mov_cost,
                     CASE WHEN :v_factor = 0 THEN :v_mov_cost ELSE :v_mov_cost / :v_factor END);

                UPDATE STOCK_MOVEMENTS
                   SET QUANTITY_CHANGE = QUANTITY_CHANGE * :v_factor,
                       UNIT_COST = CASE WHEN :v_factor = 0 THEN UNIT_COST ELSE UNIT_COST / :v_factor END
                 WHERE ID = :v_mov_id;
            END

            FOR SELECT P.ID, P.QUANTITY, P.NET_QUANTITY, P.UNIT_COST, COALESCE(P.UNIT_CODE, '')
                FROM PRODUCTION_MATERIAL_PLANS P
                WHERE P.MATERIAL_ID = :v_mat_id
                INTO :v_plan_id, :v_plan_qty, :v_plan_net, :v_plan_cost, :v_plan_unit
            DO
            BEGIN
                INSERT INTO UNIT_CONVERSION_AUDIT
                    (RUN_ID, ENTITY_NAME, ENTITY_ID, MATERIAL_ID, OLD_UNIT_CODE, NEW_UNIT_CODE,
                     CONVERSION_FACTOR, QUANTITY_BEFORE, QUANTITY_AFTER, COST_BEFORE, COST_AFTER)
                VALUES
                    (:v_run_id, 'PRODUCTION_MATERIAL_PLANS', :v_plan_id, :v_mat_id, :v_plan_unit, :v_new_unit,
                     :v_factor, :v_plan_qty, :v_plan_qty * :v_factor, :v_plan_cost,
                     CASE WHEN :v_factor = 0 THEN :v_plan_cost ELSE :v_plan_cost / :v_factor END);

                UPDATE PRODUCTION_MATERIAL_PLANS
                   SET UNIT_CODE = :v_new_unit,
                       QUANTITY = QUANTITY * :v_factor,
                       NET_QUANTITY = NET_QUANTITY * :v_factor,
                       UNIT_COST = CASE WHEN :v_factor = 0 THEN UNIT_COST ELSE UNIT_COST / :v_factor END
                 WHERE ID = :v_plan_id;
            END
        END
    END

    UPDATE UNIT_CONVERSION_RUNS
       SET COMPLETED_AT = CURRENT_TIMESTAMP
     WHERE ID = :v_run_id;
END^
SET TERM ; ^

