/* ---- Party credits: giữ tiền / cấn trừ — KHÔNG phải phiếu thu/chi ---- */
CREATE TABLE PARTY_CREDITS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    BRANCH_ID BIGINT NOT NULL,
    CODE VARCHAR(40) CHARACTER SET ASCII NOT NULL,
    PARTY_TYPE VARCHAR(30) NOT NULL,
    PARTY_ID BIGINT NOT NULL,
    CREDIT_KIND VARCHAR(40) NOT NULL,
    ORIGINAL_AMOUNT_VND NUMERIC(18,2) NOT NULL,
    USED_AMOUNT_VND NUMERIC(18,2) DEFAULT 0 NOT NULL,
    REMAINING_AMOUNT_VND NUMERIC(18,2) NOT NULL,
    ORIGIN_DOCUMENT_TYPE VARCHAR(40) NOT NULL,
    ORIGIN_DOCUMENT_ID BIGINT NOT NULL,
    STATUS_CODE VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
    NOTES VARCHAR(500),
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_PARTY_CREDITS PRIMARY KEY (ID),
    CONSTRAINT FK_PCRED_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_PCRED_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT FK_PCRED_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_PARTY_CREDITS_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT CK_PCRED_PARTY CHECK (PARTY_TYPE IN ('SUPPLIER', 'CUSTOMER')),
    CONSTRAINT CK_PCRED_KIND CHECK (CREDIT_KIND IN (
        'SUPPLIER_RETURN_HOLD', 'CUSTOMER_RETURN_HOLD', 'MANUAL_ADJUST')),
    CONSTRAINT CK_PCRED_STATUS CHECK (STATUS_CODE IN ('OPEN', 'PARTIAL', 'USED', 'CANCELLED')),
    CONSTRAINT CK_PCRED_AMOUNTS CHECK (
        ORIGINAL_AMOUNT_VND > 0 AND USED_AMOUNT_VND >= 0 AND REMAINING_AMOUNT_VND >= 0
        AND USED_AMOUNT_VND + REMAINING_AMOUNT_VND = ORIGINAL_AMOUNT_VND),
    CONSTRAINT CK_PCRED_PARTY_ID CHECK (PARTY_ID > 0)
);

CREATE INDEX IX_PCRED_PARTY ON PARTY_CREDITS (COMPANY_ID, PARTY_TYPE, PARTY_ID, STATUS_CODE);
CREATE INDEX IX_PCRED_ORIGIN ON PARTY_CREDITS (ORIGIN_DOCUMENT_TYPE, ORIGIN_DOCUMENT_ID);

