/* Version 77: extended application permission catalog. Requires migration 76.
   Apply with Invoke-KazukoMigration.ps1. Rollback: restore the pre-migration backup.
   Existing grants remain unchanged; new sensitive permissions default to denied.
*/
SET AUTODDL OFF;
CREATE EXCEPTION EX_PERMISSION_MIGRATION 'Migration 77 requires migration 76';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
    IF (NOT EXISTS (SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 76)) THEN
        EXCEPTION EX_PERMISSION_MIGRATION;
END^
SET TERM ; ^

-- Step 6: Seed
INSERT INTO GROUP_PERMISSIONS
    (COMPANY_ID, GROUP_ID, FUNCTION_CODE, CAN_VIEW, CAN_ADD, CAN_EDIT, CAN_DELETE, IS_LOCKED)
SELECT G.COMPANY_ID, G.ID, F.CODE,
       CASE WHEN G.CODE = 'ADMIN' OR (G.CODE = 'CASHIER' AND F.CODE IN ('INV_STOCK_VIEW', 'INV_HISTORY', 'SALES_HISTORY')) THEN TRUE ELSE FALSE END,
       CASE WHEN G.CODE = 'ADMIN' THEN TRUE ELSE FALSE END,
       CASE WHEN G.CODE = 'ADMIN' THEN TRUE ELSE FALSE END,
       CASE WHEN G.CODE = 'ADMIN' THEN TRUE ELSE FALSE END,
       FALSE
FROM USER_GROUPS G
CROSS JOIN (
    SELECT CAST('INV_STOCK_VIEW' AS VARCHAR(60)) AS CODE FROM RDB$DATABASE UNION ALL
    SELECT 'INV_HISTORY' FROM RDB$DATABASE UNION ALL
    SELECT 'INV_SALES_INTAKE' FROM RDB$DATABASE UNION ALL
    SELECT 'INV_REVERSE' FROM RDB$DATABASE UNION ALL
    SELECT 'PROD_COMPLETE' FROM RDB$DATABASE UNION ALL
    SELECT 'PROD_CANCEL' FROM RDB$DATABASE UNION ALL
    SELECT 'PROD_QC' FROM RDB$DATABASE UNION ALL
    SELECT 'SALES_HISTORY' FROM RDB$DATABASE UNION ALL
    SELECT 'SALES_PRICE_OVERRIDE' FROM RDB$DATABASE UNION ALL
    SELECT 'SALES_DEBT_APPROVE' FROM RDB$DATABASE UNION ALL
    SELECT 'SALES_CHANGE_EMPLOYEE' FROM RDB$DATABASE UNION ALL
    SELECT 'FIN_REVERSE' FROM RDB$DATABASE UNION ALL
    SELECT 'DATA_EXPORT' FROM RDB$DATABASE
) F
WHERE NOT EXISTS (SELECT 1 FROM GROUP_PERMISSIONS P WHERE P.GROUP_ID = G.ID AND P.FUNCTION_CODE = F.CODE);

DROP EXCEPTION EX_PERMISSION_MIGRATION;
