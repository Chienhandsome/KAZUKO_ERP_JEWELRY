    CONSTRAINT CK_RD_PARTY_XOR CHECK (
        (PARTY_TYPE = 'CUSTOMER' AND CUSTOMER_ID IS NOT NULL AND EXTERNAL_WORKER_ID IS NULL)
        OR (PARTY_TYPE = 'EXTERNAL_WORKER' AND EXTERNAL_WORKER_ID IS NOT NULL AND CUSTOMER_ID IS NULL))
