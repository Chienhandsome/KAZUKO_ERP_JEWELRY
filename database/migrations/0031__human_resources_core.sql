    ALLOWANCE NUMERIC(18,2) DEFAULT 0 NOT NULL,
    NOTES VARCHAR(1000),
    STATUS_CODE VARCHAR(20) DEFAULT 'WORKING' NOT NULL,
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_HR_EMPLOYEES PRIMARY KEY (ID),
    CONSTRAINT FK_HR_EMP_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_HR_EMP_BRANCH FOREIGN KEY (CREATED_BRANCH_ID) REFERENCES BRANCHES (ID),
    CONSTRAINT FK_HR_EMP_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_HR_EMP_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_HR_EMP_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT UQ_HR_EMP_COMP_ID UNIQUE (COMPANY_ID, ID),
    CONSTRAINT CK_HR_EMP_BASE_SALARY CHECK (BASE_SALARY >= 0),
    CONSTRAINT CK_HR_EMP_ALLOWANCE CHECK (ALLOWANCE >= 0),
    CONSTRAINT CK_HR_EMP_STATUS CHECK (STATUS_CODE IN ('WORKING', 'ON_LEAVE', 'TERMINATED'))
);

CREATE UNIQUE INDEX UQ_HR_EMP_ATTENDANCE ON HR_EMPLOYEES (COMPANY_ID, ATTENDANCE_CODE)
