-- Step 3: HR_DEPARTMENTS
CREATE TABLE HR_DEPARTMENTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    CODE VARCHAR(30) CHARACTER SET ASCII NOT NULL,
    NAME VARCHAR(150) NOT NULL,
    DESCRIPTION VARCHAR(500),
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_HR_DEPARTMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_HR_DEPT_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_HR_DEPT_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_HR_DEPT_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_HR_DEPT_CODE UNIQUE (COMPANY_ID, CODE),
    CONSTRAINT UQ_HR_DEPT_COMP_ID UNIQUE (COMPANY_ID, ID)
);

CREATE INDEX IX_HR_DEPT_ACTIVE ON HR_DEPARTMENTS (COMPANY_ID, IS_ACTIVE, DISPLAY_ORDER);

