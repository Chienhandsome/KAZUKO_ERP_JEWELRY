-- Step 2: Work shifts
CREATE TABLE HR_WORK_SHIFTS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    NAME VARCHAR(50) NOT NULL,
    START_TIME TIME,
    END_TIME TIME,
    DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
    IS_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_HR_SHIFTS PRIMARY KEY (ID),
    CONSTRAINT FK_HR_SHIFTS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_HR_SHIFTS_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_HR_SHIFTS_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_HR_SHIFTS_NAME UNIQUE (COMPANY_ID, NAME)
);

CREATE INDEX IX_HR_SHIFTS_ACTIVE ON HR_WORK_SHIFTS (COMPANY_ID, IS_ACTIVE, DISPLAY_ORDER);

-- Step 3: Attendance records (only non-default statuses are stored)
CREATE TABLE HR_ATTENDANCE_RECORDS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    COMPANY_ID BIGINT NOT NULL,
    EMPLOYEE_ID BIGINT NOT NULL,
    SHIFT_ID BIGINT NOT NULL,
    WORK_DATE DATE NOT NULL,
    STATUS_CODE VARCHAR(20) NOT NULL,
    CREATED_BY BIGINT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY BIGINT,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT PK_HR_ATT PRIMARY KEY (ID),
    CONSTRAINT FK_HR_ATT_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES (ID),
    CONSTRAINT FK_HR_ATT_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES HR_EMPLOYEES (ID),
    CONSTRAINT FK_HR_ATT_SHIFT FOREIGN KEY (SHIFT_ID) REFERENCES HR_WORK_SHIFTS (ID),
    CONSTRAINT FK_HR_ATT_CREATE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
    CONSTRAINT FK_HR_ATT_UPDATE_USER FOREIGN KEY (UPDATED_BY) REFERENCES USERS (ID),
    CONSTRAINT UQ_HR_ATT_CELL UNIQUE (COMPANY_ID, EMPLOYEE_ID, SHIFT_ID, WORK_DATE),
    CONSTRAINT CK_HR_ATT_STATUS CHECK (STATUS_CODE IN ('WORK', 'PAID_LEAVE', 'UNPAID_LEAVE'))
);

CREATE INDEX IX_HR_ATT_DATE ON HR_ATTENDANCE_RECORDS (COMPANY_ID, WORK_DATE);
CREATE INDEX IX_HR_ATT_EMPLOYEE ON HR_ATTENDANCE_RECORDS (COMPANY_ID, EMPLOYEE_ID, WORK_DATE);

