CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed'^

EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 42 INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu phien ban 42.';

    SELECT COUNT(*) FROM LOCATIONS
    WHERE CODE = 'QUAY_TRUNG_TAM' AND IS_ACTIVE = TRUE
    INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'QUAY_TRUNG_TAM van dang hoat dong.';

    SELECT COUNT(*)
    FROM FINISHED_PRODUCTS F
    JOIN LOCATIONS L ON L.ID = F.LOCATION_ID
    WHERE L.CODE = 'QUAY_TRUNG_TAM'
    INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Van con thanh pham tai QUAY_TRUNG_TAM.';

    SELECT COUNT(*) FROM LOCATIONS
    WHERE CODE = 'KHO_THANH_PHAM' AND IS_ACTIVE = TRUE
      AND INVENTORY_SCOPE = 'FINISHED_GOODS'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'KHO_THANH_PHAM khong san sang.';
END^

DROP EXCEPTION EX_VERIFY_FAILED^
SET TERM ; ^
