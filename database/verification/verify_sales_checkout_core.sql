/*
Verification for migration 51 — sales checkout core, snapshots, offsets and CARD.
Run only against a restored/copy database after Invoke-KazukoMigration.ps1.
*/

SET AUTODDL OFF;

CREATE EXCEPTION EX_VERIFY_FAILED 'Sales checkout schema verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 51 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu version 51.';

    SELECT COUNT(*) FROM RDB$RELATIONS
    WHERE RDB$RELATION_NAME IN (
        'SALES_CHECKOUTS', 'SALES_OLD_GOLD_LINES', 'SALES_CHECKOUT_OFFSETS')
      AND COALESCE(RDB$SYSTEM_FLAG, 0) = 0
    INTO :v_cnt;
    IF (:v_cnt <> 3) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu bang sales checkout core.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'SALES_CHECKOUTS'
      AND RDB$FIELD_NAME IN (
        'ID', 'COMPANY_ID', 'BRANCH_ID', 'CODE', 'CHECKOUT_TYPE',
        'DOCUMENT_DATE', 'CUSTOMER_ID', 'SALESPERSON_ID', 'SOURCE_LOCATION_ID',
        'OLD_GOLD_DESTINATION_LOCATION_ID', 'SALE_GROSS_VND',
        'OLD_GOLD_TOTAL_VND', 'DISCOUNT_AMOUNT_VND', 'NET_AMOUNT_VND',
        'SALES_ORDER_ID', 'OLD_GOLD_STOCK_DOCUMENT_ID',
        'FINANCIAL_SETTLEMENT_ID', 'RECEIVABLE_DEBT_ID',
        'CLIENT_REQUEST_ID', 'REQUEST_HASH', 'STATUS_CODE', 'NOTES',
        'CREATED_BY', 'CREATED_AT')
    INTO :v_cnt;
    IF (:v_cnt <> 24) THEN
        EXCEPTION EX_VERIFY_FAILED 'SALES_CHECKOUTS thieu cot bat buoc.';

    SELECT COUNT(*)
    FROM RDB$RELATION_FIELDS RF
    JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
    WHERE RF.RDB$RELATION_NAME = 'SALES_CHECKOUTS'
      AND RF.RDB$FIELD_NAME = 'CLIENT_REQUEST_ID'
      AND RF.RDB$NULL_FLAG = 1
      AND F.RDB$FIELD_TYPE = 14
      AND F.RDB$FIELD_LENGTH = 36
    INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'CLIENT_REQUEST_ID phai la CHAR(36) NOT NULL.';

    SELECT COUNT(*)
    FROM RDB$RELATION_FIELDS RF
    JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
    WHERE RF.RDB$RELATION_NAME = 'SALES_CHECKOUTS'
      AND RF.RDB$FIELD_NAME = 'REQUEST_HASH'
      AND RF.RDB$NULL_FLAG = 1
      AND F.RDB$FIELD_TYPE = 14
      AND F.RDB$FIELD_LENGTH = 64
    INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'REQUEST_HASH phai la CHAR(64) NOT NULL.';

    SELECT COUNT(*)
    FROM RDB$RELATION_FIELDS RF
    JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
    WHERE RF.RDB$RELATION_NAME = 'SALES_CHECKOUTS'
      AND RF.RDB$FIELD_NAME IN (
        'SALE_GROSS_VND', 'OLD_GOLD_TOTAL_VND',
        'DISCOUNT_AMOUNT_VND', 'NET_AMOUNT_VND')
      AND RF.RDB$NULL_FLAG = 1
      AND F.RDB$FIELD_SCALE = -2
    INTO :v_cnt;
    IF (:v_cnt <> 4) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu bon cot tong tien NUMERIC(18,2) NOT NULL.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'SALES_OLD_GOLD_LINES'
      AND RDB$FIELD_NAME IN (
        'ID', 'CHECKOUT_ID', 'LINE_NUMBER', 'MATERIAL_ID',
        'STOCK_DOCUMENT_LINE_ID', 'ITEM_QUANTITY', 'TOTAL_WEIGHT_CHI',
        'STONE_WEIGHT_CHI', 'IMPURITY_WEIGHT_CHI', 'GOLD_WEIGHT_CHI',
        'VALUE_PERCENT', 'CONVERTED_WEIGHT_CHI', 'SOURCE_BUY_PRICE_PER_CHI',
        'APPLIED_BUY_PRICE_PER_CHI', 'AMOUNT_VND', 'IS_PRICE_OVERRIDE',
        'PRICE_OVERRIDE_REASON', 'NOTES')
    INTO :v_cnt;
    IF (:v_cnt <> 18) THEN
        EXCEPTION EX_VERIFY_FAILED 'SALES_OLD_GOLD_LINES thieu input/derived/snapshot.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'SALES_CHECKOUT_OFFSETS'
      AND RDB$FIELD_NAME IN (
        'ID', 'CHECKOUT_ID', 'SALES_ORDER_ID', 'STOCK_DOCUMENT_ID',
        'AMOUNT_VND', 'CREATED_AT')
    INTO :v_cnt;
    IF (:v_cnt <> 6) THEN
        EXCEPTION EX_VERIFY_FAILED 'SALES_CHECKOUT_OFFSETS thieu cot bat buoc.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'SALES_ORDER_ITEMS'
      AND RDB$FIELD_NAME IN (
        'FINISHED_PRODUCT_ID', 'SOURCE_GOLD_PRICE_PER_CHI',
        'APPLIED_GOLD_PRICE_PER_CHI', 'SOURCE_LABOR_AMOUNT_VND',
        'APPLIED_LABOR_AMOUNT_VND', 'SOURCE_STONE_AMOUNT_VND',
        'APPLIED_STONE_AMOUNT_VND', 'IS_PRICE_OVERRIDE',
        'PRICE_OVERRIDE_REASON')
    INTO :v_cnt;
    IF (:v_cnt <> 9) THEN
        EXCEPTION EX_VERIFY_FAILED 'SALES_ORDER_ITEMS thieu snapshot gia checkout.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'ORDER_PAYMENTS'
      AND RDB$FIELD_NAME IN (
        'FINANCIAL_SETTLEMENT_ID', 'FINANCIAL_SETTLEMENT_ALLOCATION_ID',
        'CASH_VOUCHER_ID')
    INTO :v_cnt;
    IF (:v_cnt <> 3) THEN
        EXCEPTION EX_VERIFY_FAILED 'ORDER_PAYMENTS thieu linkage settlement/voucher.';

    SELECT COUNT(*) FROM RDB$RELATION_CONSTRAINTS
    WHERE RDB$CONSTRAINT_NAME IN (
        'PK_SALES_CHECKOUTS', 'FK_SC_COMPANY', 'FK_SC_BRANCH',
        'FK_SC_CUSTOMER', 'FK_SC_SALESPERSON', 'FK_SC_SOURCE_LOCATION',
        'FK_SC_OLD_GOLD_LOCATION', 'FK_SC_SALES_ORDER',
        'FK_SC_OLD_GOLD_DOCUMENT', 'FK_SC_SETTLEMENT', 'FK_SC_RECEIVABLE',
        'FK_SC_CREATED_BY', 'UQ_SC_CODE', 'UQ_SC_CLIENT_REQUEST',
        'CK_SC_TYPE', 'CK_SC_STATUS', 'CK_SC_TOTALS', 'CK_SC_REQUEST_HASH',
        'PK_SALES_OLD_GOLD_LINES', 'FK_SOGL_CHECKOUT', 'FK_SOGL_MATERIAL',
        'FK_SOGL_STOCK_LINE', 'UQ_SOGL_LINE', 'UQ_SOGL_STOCK_LINE',
        'CK_SOGL_LINE_NUMBER', 'CK_SOGL_ITEM_QUANTITY', 'CK_SOGL_WEIGHTS',
        'CK_SOGL_PRICES', 'CK_SOGL_OVERRIDE',
        'PK_SALES_CHECKOUT_OFFSETS', 'FK_SCO_CHECKOUT', 'FK_SCO_SALES_ORDER',
        'FK_SCO_STOCK_DOCUMENT', 'UQ_SCO_CHECKOUT', 'CK_SCO_AMOUNT',
        'FK_SOI_FINISHED_PRODUCT', 'CK_SOI_PRICE_SNAPSHOTS',
        'CK_SOI_PRICE_OVERRIDE', 'FK_OP_SETTLEMENT', 'FK_OP_SETTLEMENT_ALLOC',
        'FK_OP_CASH_VOUCHER', 'CK_OP_SETTLEMENT_LINK')
    INTO :v_cnt;
    IF (:v_cnt <> 42) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu PK/FK/unique/check cua migration 51.';

    SELECT COUNT(DISTINCT RC.RDB$CONSTRAINT_NAME)
    FROM RDB$RELATION_CONSTRAINTS RC
    JOIN RDB$CHECK_CONSTRAINTS CC
      ON CC.RDB$CONSTRAINT_NAME = RC.RDB$CONSTRAINT_NAME
    JOIN RDB$TRIGGERS T
      ON T.RDB$TRIGGER_NAME = CC.RDB$TRIGGER_NAME
    WHERE RC.RDB$CONSTRAINT_NAME IN ('CK_SOGL_OVERRIDE', 'CK_SOI_PRICE_OVERRIDE')
      AND T.RDB$TRIGGER_SOURCE CONTAINING 'PRICE_OVERRIDE_REASON IS NOT NULL'
    INTO :v_cnt;
    IF (:v_cnt <> 2) THEN
        EXCEPTION EX_VERIFY_FAILED 'Override gia phai bat buoc ly do khac NULL.';

    SELECT COUNT(*) FROM RDB$INDICES
    WHERE RDB$INDEX_NAME IN (
        'IX_SC_BRANCH_DATE', 'IX_SC_CUSTOMER', 'IX_SC_SALESPERSON',
        'IX_SC_SALES_ORDER', 'IX_SC_OLD_GOLD_DOC', 'IX_SC_SETTLEMENT',
        'IX_SC_RECEIVABLE', 'IX_SOGL_CHECKOUT', 'IX_SOGL_MATERIAL',
        'IX_SOGL_STOCK_LINE', 'IX_SCO_SALES_ORDER', 'IX_SCO_STOCK_DOCUMENT',
        'IX_SOI_FINISHED_PRODUCT', 'IX_OP_SETTLEMENT', 'IX_OP_VOUCHER',
        'UQ_OP_SETTLEMENT_ALLOC')
      AND COALESCE(RDB$INDEX_INACTIVE, 0) = 0
    INTO :v_cnt;
    IF (:v_cnt <> 16) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu index cua migration 51.';

    SELECT COUNT(*) FROM RDB$INDICES
    WHERE RDB$INDEX_NAME = 'UQ_OP_SETTLEMENT_ALLOC'
      AND RDB$UNIQUE_FLAG = 1
      AND COALESCE(RDB$INDEX_INACTIVE, 0) = 0
    INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'UQ_OP_SETTLEMENT_ALLOC phai la unique index.';

    SELECT COUNT(*)
    FROM RDB$RELATION_CONSTRAINTS RC
    JOIN RDB$CHECK_CONSTRAINTS CC
      ON CC.RDB$CONSTRAINT_NAME = RC.RDB$CONSTRAINT_NAME
    JOIN RDB$TRIGGERS T
      ON T.RDB$TRIGGER_NAME = CC.RDB$TRIGGER_NAME
    WHERE RC.RDB$CONSTRAINT_NAME = 'CK_SC_TOTALS'
      AND T.RDB$TRIGGER_SOURCE CONTAINING
          'NET_AMOUNT_VND = SALE_GROSS_VND - DISCOUNT_AMOUNT_VND - OLD_GOLD_TOTAL_VND'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'NET_AMOUNT_VND khong duoc bao ve theo cong thuc co dau.';

    SELECT COUNT(*)
    FROM RDB$RELATION_CONSTRAINTS RC
    JOIN RDB$CHECK_CONSTRAINTS CC
      ON CC.RDB$CONSTRAINT_NAME = RC.RDB$CONSTRAINT_NAME
    JOIN RDB$TRIGGERS T
      ON T.RDB$TRIGGER_NAME = CC.RDB$TRIGGER_NAME
    WHERE RC.RDB$CONSTRAINT_NAME = 'CK_STOCK_PURPOSE'
      AND T.RDB$TRIGGER_SOURCE CONTAINING 'RETAIL_SALE'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'CK_STOCK_PURPOSE thieu RETAIL_SALE.';

    SELECT COUNT(DISTINCT RC.RDB$CONSTRAINT_NAME)
    FROM RDB$RELATION_CONSTRAINTS RC
    JOIN RDB$CHECK_CONSTRAINTS CC
      ON CC.RDB$CONSTRAINT_NAME = RC.RDB$CONSTRAINT_NAME
    JOIN RDB$TRIGGERS T
      ON T.RDB$TRIGGER_NAME = CC.RDB$TRIGGER_NAME
    WHERE RC.RDB$CONSTRAINT_NAME IN (
        'CK_CV_METHOD', 'CK_CV_METHOD_TARGET',
        'CK_SDP_METHOD', 'CK_SDP_METHOD_TARGET',
        'CK_FSA_METHOD', 'CK_FSA_METHOD_TARGET',
        'CK_PDPA_METHOD', 'CK_PDPA_METHOD_TARGET',
        'CK_ORDER_PAYMENT_METHOD')
      AND T.RDB$TRIGGER_SOURCE CONTAINING 'CARD'
    INTO :v_cnt;
    IF (:v_cnt <> 9) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu CARD trong payment method/target constraints.';

    SELECT COUNT(*) FROM PERMISSIONS
    WHERE CODE IN (
        'sales.checkout.post', 'sales.price.override', 'sales.debt.approve',
        'sales.salesperson.change', 'sales.history.read', 'sales.receipt.print')
      AND MODULE_CODE = 'SALES'
    INTO :v_cnt;
    IF (:v_cnt <> 6) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu sau sales permissions.';

    SELECT COUNT(*)
    FROM ROLE_PERMISSIONS RP
    JOIN ROLES R ON R.ID = RP.ROLE_ID
    JOIN PERMISSIONS P ON P.ID = RP.PERMISSION_ID
    WHERE RP.IS_ALLOWED = TRUE
      AND ((R.CODE IN ('ADMIN', 'MANAGER') AND P.CODE IN (
            'sales.checkout.post', 'sales.price.override', 'sales.debt.approve',
            'sales.salesperson.change', 'sales.history.read', 'sales.receipt.print'))
        OR (R.CODE = 'SALE' AND P.CODE IN (
            'sales.checkout.post', 'sales.history.read', 'sales.receipt.print')))
    INTO :v_cnt;
    IF (:v_cnt <> 15) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu role-permission sales mac dinh.';

    SELECT COUNT(*) FROM BRANCHES B
    WHERE NOT EXISTS (
        SELECT 1 FROM DOCUMENT_SEQUENCES S
        WHERE S.DOCUMENT_TYPE = 'SALES_CHECKOUT'
          AND S.BRANCH_ID = B.ID
          AND S.YEAR_NO = EXTRACT(YEAR FROM CURRENT_DATE))
    INTO :v_cnt;
    IF (:v_cnt <> 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu sequence SALES_CHECKOUT theo chi nhanh/nam.';

    SELECT COUNT(*) FROM BRANCHES B
    WHERE NOT EXISTS (
        SELECT 1 FROM DOCUMENT_SEQUENCES S
        WHERE S.DOCUMENT_TYPE = 'SALES_OLD_GOLD_PURCHASE'
          AND S.BRANCH_ID = B.ID
          AND S.YEAR_NO = EXTRACT(YEAR FROM CURRENT_DATE))
    INTO :v_cnt;
    IF (:v_cnt <> 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu sequence SALES_OLD_GOLD_PURCHASE theo chi nhanh/nam.';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
