SET AUTODDL OFF;

CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 35 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu version 35.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'CASH_VOUCHERS' AND RDB$FIELD_NAME = 'SOURCE_ALLOCATION_TYPE' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu CASH_VOUCHERS.SOURCE_ALLOCATION_TYPE.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'CASH_VOUCHERS' AND RDB$FIELD_NAME = 'SOURCE_ALLOCATION_ID' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu CASH_VOUCHERS.SOURCE_ALLOCATION_ID.';

    SELECT COUNT(*) FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'UQ_CV_SOURCE_ALLOC' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu index UQ_CV_SOURCE_ALLOC.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINANCIAL_SETTLEMENTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINANCIAL_SETTLEMENTS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINANCIAL_SETTLEMENT_ALLOCATIONS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINANCIAL_SETTLEMENT_ALLOCATIONS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINANCIAL_SETTLEMENT_APPLICATIONS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINANCIAL_SETTLEMENT_APPLICATIONS.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'FINANCIAL_SETTLEMENTS' AND RDB$FIELD_NAME = 'SETTLEMENT_TYPE' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINANCIAL_SETTLEMENTS.SETTLEMENT_TYPE.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'FINANCIAL_SETTLEMENT_ALLOCATIONS' AND RDB$FIELD_NAME = 'CASH_VOUCHER_ID' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINANCIAL_SETTLEMENT_ALLOCATIONS.CASH_VOUCHER_ID.';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
COMMIT;
