SELECT COMPANY_ID, COUNT(*) AS WALK_IN_RECORDS
FROM CUSTOMERS WHERE UPPER(TRIM(CODE)) IN ('KH-VL','WALK_IN','KHACH_LE')
GROUP BY COMPANY_ID HAVING COUNT(*) > 1;
SELECT ID, COMPANY_ID, CODE, NAME, IS_ACTIVE FROM CUSTOMERS
WHERE UPPER(TRIM(CODE)) IN ('KH-VL','WALK_IN','KHACH_LE') AND IS_ACTIVE = FALSE;
SELECT C.ID, C.CODE, O.ID AS ORDER_ID, O.ORDER_TYPE, O.STATUS_CODE,
       O.GRAND_TOTAL - COALESCE((SELECT SUM(CASE P.PAYMENT_TYPE WHEN 'REFUND' THEN -P.AMOUNT ELSE P.AMOUNT END)
           FROM ORDER_PAYMENTS P WHERE P.ORDER_ID=O.ID AND P.IS_VOIDED=FALSE),0)
       - COALESCE((SELECT SUM(X.AMOUNT_VND) FROM SALES_CHECKOUT_OFFSETS X WHERE X.SALES_ORDER_ID=O.ID),0) AS BALANCE
FROM CUSTOMERS C JOIN SALES_ORDERS O ON O.CUSTOMER_ID=C.ID
WHERE UPPER(TRIM(C.CODE)) IN ('KH-VL','WALK_IN','KHACH_LE') AND O.STATUS_CODE NOT IN ('DRAFT','CANCELLED')
AND (O.ORDER_TYPE='CUSTOM' OR O.GRAND_TOTAL >
    COALESCE((SELECT SUM(CASE P.PAYMENT_TYPE WHEN 'REFUND' THEN -P.AMOUNT ELSE P.AMOUNT END)
        FROM ORDER_PAYMENTS P WHERE P.ORDER_ID=O.ID AND P.IS_VOIDED=FALSE),0)
    + COALESCE((SELECT SUM(X.AMOUNT_VND) FROM SALES_CHECKOUT_OFFSETS X WHERE X.SALES_ORDER_ID=O.ID),0));
