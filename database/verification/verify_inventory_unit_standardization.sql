SET AUTODDL OFF;

CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'UNIT_CONVERSION_RUNS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu UNIT_CONVERSION_RUNS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'UNIT_CONVERSION_AUDIT' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu UNIT_CONVERSION_AUDIT.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'UNIT_CONVERSION_EXCEPTIONS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu UNIT_CONVERSION_EXCEPTIONS.';

    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 33 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu version 33.';

    SELECT COUNT(*) FROM MATERIALS
     WHERE MATERIAL_TYPE = 'GOLD'
       AND UPPER(TRIM(UNIT_CODE)) <> 'CHI'
       AND ID NOT IN (
           SELECT MATERIAL_ID FROM UNIT_CONVERSION_EXCEPTIONS
            WHERE MATERIAL_ID IS NOT NULL AND ENTITY_NAME = 'MATERIALS')
      INTO :v_cnt;
    IF (:v_cnt > 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'GOLD chua chuan hoa CHI (ngoai exceptions).';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
COMMIT;
