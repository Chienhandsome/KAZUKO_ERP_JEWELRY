SET AUTODDL OFF;
CREATE EXCEPTION EX_VERIFY_FAILED 'Finished product group verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM RDB$RELATIONS
    WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCT_GROUPS'
    INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu bang FINISHED_PRODUCT_GROUPS.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
    WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCTS'
      AND RDB$FIELD_NAME = 'FINISHED_PRODUCT_GROUP_ID'
    INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINISHED_PRODUCTS.FINISHED_PRODUCT_GROUP_ID.';

    SELECT COUNT(*) FROM FINISHED_PRODUCT_GROUPS G
    JOIN COMPANIES C ON C.ID = G.COMPANY_ID
    WHERE C.CODE = 'KAZUKO'
      AND G.CODE IN ('BRACELET', 'EARRING', 'RING', 'NECKLACE')
      AND G.IS_ACTIVE = TRUE
    INTO :v_cnt;
    IF (:v_cnt <> 4) THEN
        EXCEPTION EX_VERIFY_FAILED 'Sai du lieu 4 nhom thanh pham.';

    SELECT COUNT(*) FROM FINISHED_PRODUCTS F
    LEFT JOIN FINISHED_PRODUCT_GROUPS G
      ON G.COMPANY_ID = F.COMPANY_ID AND G.ID = F.FINISHED_PRODUCT_GROUP_ID
    WHERE F.FINISHED_PRODUCT_GROUP_ID IS NOT NULL AND G.ID IS NULL
    INTO :v_cnt;
    IF (:v_cnt <> 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Co thanh pham tham chieu nhom khong hop le.';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
