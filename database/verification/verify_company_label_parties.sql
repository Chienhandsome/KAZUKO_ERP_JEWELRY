SET AUTODDL OFF;
CREATE EXCEPTION EX_VERIFY_LABEL_PARTIES 'Company label parties verification failed';
SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE N INTEGER;
BEGIN
 SELECT COUNT(*) FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='COMPANIES'
 AND RDB$FIELD_NAME IN ('DISTRIBUTOR_NAME','DISTRIBUTOR_ADDRESS','MANUFACTURER_NAME','MANUFACTURER_ADDRESS','COUNTRY_OF_ORIGIN') INTO :N;
 IF (N <> 5) THEN EXCEPTION EX_VERIFY_LABEL_PARTIES;
 IF (NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=85 AND CHAR_LENGTH(CHECKSUM_VALUE)=64)) THEN EXCEPTION EX_VERIFY_LABEL_PARTIES;
END^
SET TERM ; ^
DROP EXCEPTION EX_VERIFY_LABEL_PARTIES;
ROLLBACK;
