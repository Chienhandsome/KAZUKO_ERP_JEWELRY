SET AUTODDL OFF;
SET TERM ^ ;
EXECUTE BLOCK AS
 DECLARE N INTEGER;
BEGIN
 SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME IN ('INV_COUNTS','INV_COUNT_LINES') INTO :N;
 IF(N<>2)THEN EXCEPTION EX_COUNT_SCHEMA 'Missing count tables';
 SELECT COUNT(*) FROM RDB$RELATION_FIELDS WHERE
  (RDB$RELATION_NAME='LOCATIONS' AND RDB$FIELD_NAME='COUNT_REV') OR
  (RDB$RELATION_NAME IN ('STOCK_BALANCES','FINISHED_PRODUCTS') AND RDB$FIELD_NAME='COUNT_TOKEN') OR
  (RDB$RELATION_NAME='INV_COUNT_LINES' AND RDB$FIELD_NAME='NEEDS_RECOUNT') INTO :N;
 IF(N<>4)THEN EXCEPTION EX_COUNT_SCHEMA 'Missing count revision/token fields';
 SELECT COUNT(*) FROM RDB$TRIGGERS WHERE RDB$TRIGGER_NAME IN ('BU_COUNT_BAL_TOKEN','BU_COUNT_FP_TOKEN','AU_ID_COUNT_BAL','AU_ID_COUNT_FP') AND RDB$TRIGGER_INACTIVE=0 INTO :N;
 IF(N<>4)THEN EXCEPTION EX_COUNT_SCHEMA 'Missing count tracking triggers';
 SELECT COUNT(*) FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_NAME IN ('UQ_INV_COUNT_CODE','UQ_INV_COUNT_REQUEST','UQ_INV_COUNT_ITEM','CK_INV_COUNT_SERIAL','CK_INV_COUNT_ID') INTO :N;
 IF(N<>5)THEN EXCEPTION EX_COUNT_SCHEMA 'Missing count constraints';
 IF(NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=90))THEN EXCEPTION EX_COUNT_SCHEMA 'Missing schema ledger 90';
END^
SET TERM ; ^
ROLLBACK;
