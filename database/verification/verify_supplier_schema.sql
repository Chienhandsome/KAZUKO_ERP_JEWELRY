-- 1. Verify SCHEMA_MIGRATIONS ledger
SELECT 
    VERSION_NO,
    MIGRATION_NAME,
    CHECKSUM_VALUE,
    APPLIED_AT
FROM SCHEMA_MIGRATIONS
WHERE VERSION_NO = 30;

-- 2. Verify Table Existence (SUPPLIER_GROUPS, SUPPLIERS)
SELECT 
    RDB$RELATION_NAME AS TABLE_NAME
FROM RDB$RELATIONS
WHERE RDB$SYSTEM_FLAG = 0
  AND RDB$RELATION_NAME IN ('SUPPLIER_GROUPS', 'SUPPLIERS')
ORDER BY RDB$RELATION_NAME;

-- 3. Verify SUPPLIER_GROUPS Columns
SELECT 
    RDB$FIELD_POSITION AS POS,
    RDB$FIELD_NAME AS FIELD_NAME,
    RDB$NULL_FLAG AS NOT_NULL
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME = 'SUPPLIER_GROUPS'
ORDER BY RDB$FIELD_POSITION;

-- 4. Verify SUPPLIERS Columns
SELECT 
    RDB$FIELD_POSITION AS POS,
    RDB$FIELD_NAME AS FIELD_NAME,
    RDB$NULL_FLAG AS NOT_NULL
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME = 'SUPPLIERS'
ORDER BY RDB$FIELD_POSITION;

-- 5. Verify STOCK_DOCUMENTS SUPPLIER_ID column
SELECT 
    RDB$FIELD_POSITION AS POS,
    RDB$FIELD_NAME AS FIELD_NAME,
    RDB$NULL_FLAG AS NOT_NULL
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME = 'STOCK_DOCUMENTS'
  AND RDB$FIELD_NAME = 'SUPPLIER_ID';

-- 6. Verify Constraints on SUPPLIERS and SUPPLIER_GROUPS
SELECT 
    RC.RDB$CONSTRAINT_NAME AS CONSTRAINT_NAME,
    RC.RDB$CONSTRAINT_TYPE AS CONSTRAINT_TYPE,
    RC.RDB$RELATION_NAME AS TABLE_NAME
FROM RDB$RELATION_CONSTRAINTS RC
WHERE RC.RDB$RELATION_NAME IN ('SUPPLIER_GROUPS', 'SUPPLIERS')
ORDER BY RC.RDB$RELATION_NAME, RC.RDB$CONSTRAINT_TYPE, RC.RDB$CONSTRAINT_NAME;

-- 7. Verify Foreign Key on STOCK_DOCUMENTS (FK_STOCK_DOC_SUPPLIER)
SELECT 
    RC.RDB$CONSTRAINT_NAME AS CONSTRAINT_NAME,
    RC.RDB$CONSTRAINT_TYPE AS CONSTRAINT_TYPE,
    RC.RDB$RELATION_NAME AS TABLE_NAME
FROM RDB$RELATION_CONSTRAINTS RC
WHERE RC.RDB$RELATION_NAME = 'STOCK_DOCUMENTS'
  AND RC.RDB$CONSTRAINT_NAME = 'FK_STOCK_DOC_SUPPLIER';

-- 8. Verify Custom Indexes
SELECT 
    RDB$INDEX_NAME AS INDEX_NAME,
    RDB$RELATION_NAME AS TABLE_NAME
FROM RDB$INDICES
WHERE RDB$INDEX_NAME IN (
    'IX_SUPPLIER_GROUPS_ACTIVE',
    'IX_SUPPLIERS_COMPANY_ACTIVE',
    'IX_SUPPLIERS_GROUP',
    'IX_SUPPLIERS_PHONE',
    'IX_SUPPLIERS_TAX_CODE',
    'IX_STOCK_DOC_SUPPLIER'
)
ORDER BY RDB$RELATION_NAME, RDB$INDEX_NAME;

-- 9. Verify Seed Data in SUPPLIER_GROUPS
SELECT 
    sg.ID,
    sg.COMPANY_ID,
    c.CODE AS COMPANY_CODE,
    sg.CODE,
    sg.NAME,
    sg.IS_ACTIVE,
    sg.IS_DEFAULT,
    sg.DISPLAY_ORDER
FROM SUPPLIER_GROUPS sg
JOIN COMPANIES c ON c.ID = sg.COMPANY_ID
ORDER BY sg.DISPLAY_ORDER;

