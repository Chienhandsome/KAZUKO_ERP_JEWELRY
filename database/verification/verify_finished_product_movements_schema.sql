SET AUTODDL OFF;

CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 36 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu version 36.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCT_MOVEMENTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINISHED_PRODUCT_MOVEMENTS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'STOCK_CRAFT_OUTPUT_LINES' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu STOCK_CRAFT_OUTPUT_LINES.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'FINISHED_PRODUCT_MOVEMENTS' AND RDB$FIELD_NAME = 'MOVEMENT_TYPE' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu FINISHED_PRODUCT_MOVEMENTS.MOVEMENT_TYPE.';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
COMMIT;
