SET TERM ^ ;
CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed'^

EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 41 INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu phien ban 41.';

    SELECT COUNT(*)
    FROM RDB$RELATION_CONSTRAINTS RC
    JOIN RDB$CHECK_CONSTRAINTS CC ON CC.RDB$CONSTRAINT_NAME = RC.RDB$CONSTRAINT_NAME
    JOIN RDB$TRIGGERS T ON T.RDB$TRIGGER_NAME = CC.RDB$TRIGGER_NAME
    WHERE RC.RDB$RELATION_NAME = 'STOCK_DOCUMENTS'
      AND RC.RDB$CONSTRAINT_NAME = 'CK_STOCK_PURPOSE'
      AND T.RDB$TRIGGER_SOURCE CONTAINING 'FINISHED_TO_SALES'
    INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'CK_STOCK_PURPOSE chua cho phep FINISHED_TO_SALES.';
END^

DROP EXCEPTION EX_VERIFY_FAILED^
SET TERM ; ^
