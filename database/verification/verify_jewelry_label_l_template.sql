SET AUTODDL OFF;
CREATE EXCEPTION EX_VERIFY_LABEL_L 'Independent L.btw template verification failed';
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
 IF (NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=86 AND CHAR_LENGTH(CHECKSUM_VALUE)=64)) THEN EXCEPTION EX_VERIFY_LABEL_L;
 IF (EXISTS(SELECT 1 FROM COMPANIES C WHERE C.IS_ACTIVE=TRUE AND NOT EXISTS(
     SELECT 1 FROM PRINT_TEMPLATES T WHERE T.COMPANY_ID=C.ID AND T.CODE='TEM_NU_TRANG_L_28X12'
     AND OCTET_LENGTH(T.CONTENT)>0 AND CHAR_LENGTH(T.CONTENT_HASH)=64))) THEN EXCEPTION EX_VERIFY_LABEL_L;
END^
SET TERM ; ^
DROP EXCEPTION EX_VERIFY_LABEL_L;
ROLLBACK;
