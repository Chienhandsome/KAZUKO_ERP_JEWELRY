SET AUTODDL OFF;

CREATE EXCEPTION EX_VERIFY_FAILED 'Schema verification failed';

SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) FROM SCHEMA_MIGRATIONS WHERE VERSION_NO = 34 INTO :v_cnt;
    IF (:v_cnt <> 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'SCHEMA_MIGRATIONS thieu version 34.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'EXTERNAL_WORKERS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu EXTERNAL_WORKERS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'CASH_FUNDS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu CASH_FUNDS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'BANK_ACCOUNTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu BANK_ACCOUNTS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'CASH_VOUCHERS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu CASH_VOUCHERS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'STOCK_DOCUMENT_PAYMENTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu STOCK_DOCUMENT_PAYMENTS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'PAYABLE_DEBTS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu PAYABLE_DEBTS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'EXTERNAL_WORKER_HOLDINGS' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu EXTERNAL_WORKER_HOLDINGS.';

    SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'STOCK_CRAFT_SETTLEMENT_LINES' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu STOCK_CRAFT_SETTLEMENT_LINES.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'STOCK_DOCUMENTS' AND RDB$FIELD_NAME = 'SOURCE_TYPE' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu STOCK_DOCUMENTS.SOURCE_TYPE.';

    SELECT COUNT(*) FROM RDB$RELATION_FIELDS
     WHERE RDB$RELATION_NAME = 'SALES_ORDERS' AND RDB$FIELD_NAME = 'FINISHED_GOODS_ISSUE_DOCUMENT_ID' INTO :v_cnt;
    IF (:v_cnt = 0) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu SALES_ORDERS.FINISHED_GOODS_ISSUE_DOCUMENT_ID.';

    SELECT COUNT(*) FROM CASH_FUNDS WHERE IS_DEFAULT = TRUE AND IS_ACTIVE = TRUE INTO :v_cnt;
    IF (:v_cnt < 1) THEN
        EXCEPTION EX_VERIFY_FAILED 'Thieu quy tien mat mac dinh.';
END^
SET TERM ; ^

DROP EXCEPTION EX_VERIFY_FAILED;
COMMIT;
