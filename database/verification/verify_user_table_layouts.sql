SET AUTODDL OFF;
CREATE EXCEPTION EX_VERIFY_TABLE_LAYOUT 'User table layout schema verification failed';
SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE VARIABLE N INTEGER;
BEGIN
 SELECT COUNT(*) FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='USER_TABLE_LAYOUTS'
 AND RDB$FIELD_NAME IN ('COMPANY_ID','USER_ID','SETTINGS_KEY','PAYLOAD','REVISION','UPDATED_AT') INTO :N;
 IF (N <> 6) THEN EXCEPTION EX_VERIFY_TABLE_LAYOUT;
 SELECT COUNT(*) FROM RDB$INDEX_SEGMENTS WHERE RDB$INDEX_NAME='PK_USER_TABLE_LAYOUTS' INTO :N;
 IF (N <> 3) THEN EXCEPTION EX_VERIFY_TABLE_LAYOUT;
 SELECT COUNT(*) FROM RDB$REF_CONSTRAINTS WHERE RDB$CONSTRAINT_NAME IN ('FK_TABLE_LAYOUT_USER','FK_TABLE_LAYOUT_COMPANY')
 AND RDB$DELETE_RULE='CASCADE' INTO :N;
 IF (N <> 2) THEN EXCEPTION EX_VERIFY_TABLE_LAYOUT;
 IF (NOT EXISTS(SELECT 1 FROM SCHEMA_MIGRATIONS WHERE VERSION_NO=93
 AND CHECKSUM_VALUE='EE0A9C3E946DA4721F2864F2C85E3ECFE970916782921F01F93FE58CAAEDEC9D')) THEN EXCEPTION EX_VERIFY_TABLE_LAYOUT;
END^
SET TERM ; ^
DROP EXCEPTION EX_VERIFY_TABLE_LAYOUT;
ROLLBACK;
